/**
 * 渠道两层收尾 + 历史渠道组（11-10，P-渠道-01 附.5、P-渠道-06）的纯函数：
 * - 来源列只显示主渠道、全称不带尾巴上的竖线（主渠道显示名、渠道显示名）；
 * - 选渠道组件默认两级（主渠道 → 子渠道），全角「｜」的老数据也拆得开；
 * - 「历史渠道」组的认法（是历史渠道）；
 * - 统计按主渠道合计（合并统计）。
 */
import { describe, it, expect } from "vitest";
import { 主渠道显示名, 渠道显示名, 是历史渠道, 历史渠道分类, 历史渠道报错 } from "@/lib/enterprise/channel-main-core";
import { 合并统计, type 渠道统计 } from "@/lib/enterprise/channel-stats";
import { 两级渠道树, type 可选渠道 } from "@/components/ChannelPicker";

describe("来源列只显示主渠道、不带竖线", () => {
  it("主渠道显示名：有 platform 用它，没有按半角 / 全角竖线拆", () => {
    expect(主渠道显示名("展会|2026广交会", "展会")).toBe("展会");
    expect(主渠道显示名("展会｜2026广交会", null)).toBe("展会");
    expect(主渠道显示名("阿里国际站", "阿里国际站")).toBe("阿里国际站");
    expect(主渠道显示名("阿里国际站|", null)).toBe("阿里国际站");
    expect(主渠道显示名(null)).toBe("");
  });
  it("渠道显示名：没子渠道、或子渠道和主渠道同名，只显示主渠道；全角竖线显示成半角", () => {
    expect(渠道显示名("阿里国际站")).toBe("阿里国际站");
    expect(渠道显示名("阿里国际站|")).toBe("阿里国际站");
    expect(渠道显示名("阿里国际站｜")).toBe("阿里国际站");
    expect(渠道显示名("官网|官网")).toBe("官网");
    expect(渠道显示名("展会｜2026广交会")).toBe("展会|2026广交会");
    expect(渠道显示名("展会 | 2026广交会")).toBe("展会|2026广交会");
  });
});

describe("历史渠道组", () => {
  it("分类写「历史渠道」才算（前后空格不算），空分类、别的分类都是在售", () => {
    expect(历史渠道分类).toBe("历史渠道");
    expect(是历史渠道("历史渠道")).toBe(true);
    expect(是历史渠道(" 历史渠道 ")).toBe(true);
    expect(是历史渠道("三方平台")).toBe(false);
    expect(是历史渠道(null)).toBe(false);
    expect(是历史渠道(undefined)).toBe(false);
  });
  it("报错写清是历史渠道、新数据不能选", () => {
    expect(历史渠道报错("某平台|旧账号")).toBe("「某平台|旧账号」是历史渠道，只承载历史客户，新数据不能选");
  });
});

describe("选渠道默认两级：先主渠道再子渠道", () => {
  const 渠 = (id: string, name: string, platform: string | null, active = true): 可选渠道 => ({ id, name, attr: "公域引流", platform, active });
  it("老数据没 platform、用全角竖线的也按主渠道分组；子渠道空的直接在第一列、不带竖线", () => {
    const 树 = 两级渠道树([渠("1", "展会｜2026广交会", null), 渠("2", "展会|2025广交会", "展会"), 渠("3", "阿里国际站", "阿里国际站"), 渠("4", "官网|", null)]);
    expect(树.map((x) => x.label)).toEqual(["展会", "阿里国际站", "官网"]);
    expect(树[0].children).toEqual([
      { value: "1", label: "2026广交会", 全称: "展会|2026广交会" },
      { value: "2", label: "2025广交会", 全称: "展会|2025广交会" },
    ]);
    expect(树[1]).toEqual({ value: "3", label: "阿里国际站", 全称: "阿里国际站" });
    expect(树[2]).toEqual({ value: "4", label: "官网", 全称: "官网" });
  });
});

describe("按主渠道合计", () => {
  const 统 = (x: Partial<渠道统计>): 渠道统计 => ({
    关联线索: 0, 有效线索: 0, 关联商机: 0, 关联订单: 0, 关联项目: 0, 累计成交: [], 当前投入: [], 产出比: null, 产出比说明: "还没录投入",
    累计运营天数: 0, 线索转商机: { 分子: 0, 分母: 0, 比例: null }, 商机转订单: { 分子: 0, 分母: 0, 比例: null }, ...x,
  });
  it("个数相加，转化按分子分母加再算，钱按币种加，产出比重算，运营天数取最长", () => {
    const 合 = 合并统计([
      统({ 关联线索: 2, 有效线索: 2, 关联商机: 1, 关联项目: 3, 累计成交: [{ 币种: "CNY", 合计: 100 }], 当前投入: [{ 币种: "CNY", 合计: 50 }], 累计运营天数: 10, 线索转商机: { 分子: 1, 分母: 3, 比例: 1 / 3 } }),
      统({ 关联线索: 1, 有效线索: 1, 关联订单: 2, 关联项目: 3, 累计成交: [{ 币种: "CNY", 合计: 300 }], 当前投入: [{ 币种: "CNY", 合计: 150 }], 累计运营天数: 30, 线索转商机: { 分子: 2, 分母: 2, 比例: 1 }, 商机转订单: { 分子: 2, 分母: 2, 比例: 1 } }),
    ]);
    expect(合).toMatchObject({ 关联线索: 3, 有效线索: 3, 关联商机: 1, 关联订单: 2, 关联项目: 6, 累计运营天数: 30 });
    expect(合.累计成交).toEqual([{ 币种: "CNY", 合计: 400 }]);
    expect(合.当前投入).toEqual([{ 币种: "CNY", 合计: 200 }]);
    expect(合.产出比).toBe(2);
    expect(合.线索转商机).toEqual({ 分子: 3, 分母: 5, 比例: 0.6 });
    expect(合.商机转订单).toEqual({ 分子: 2, 分母: 2, 比例: 1 });
  });
  it("币种混了算不了产出比；一个都没有给全 0", () => {
    const 混 = 合并统计([统({ 当前投入: [{ 币种: "CNY", 合计: 1 }] }), 统({ 当前投入: [{ 币种: "USD", 合计: 1 }] })]);
    expect(混.产出比).toBeNull();
    expect(混.产出比说明).toContain("币种");
    const 空 = 合并统计([]);
    expect(空).toMatchObject({ 关联项目: 0, 产出比: null, 产出比说明: "还没录投入", 累计运营天数: 0 });
    expect(空.线索转商机.比例).toBeNull();
  });
});
