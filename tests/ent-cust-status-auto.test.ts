/**
 * 企业版客户状态按项目自动算（10-30，lib/enterprise/cust-status-auto.ts 纯函数）。
 *   - 交付个数：1 交付、2 复购、≥3 忠诚，有交付的不看别的项目
 *   - 没交付：异常 > 丢单 > 流失 > 成交（首款支付 / 进了订单）> 意向（进了商机）> 潜在（都在线索）
 *   - 在推项目优先（重复咨询第一步，11-23）：名下有在推项目（没结局、不在公海）时按在推项目定，已结束的丢单 / 流失不再压过它；交付、异常照旧最先
 *   - 判无效终判「重复线索」的那条（不算）不参与
 *   - 没项目 = null；软删的项目不算
 *   - 仅记录用（X-147，来源仅记录用、还停在 线索 · 潜客培育）不参与、不算在推；只剩它 = null 且 只剩仅记录用（写库那一半不清旧值）；推进出去照常算
 */
import { describe, it, expect } from "vitest";
import { 算客户状态, 在推, 只剩仅记录用, 客户状态序号 as 序, 客户状态id } from "@/lib/enterprise/cust-status-auto";
import { 仅记录用来源 } from "@/lib/project/system-created";
import { 字典定义 } from "@/lib/enterprise/dict-kinds";

const 项 = (phase: string, node: string, result: string | null = null, deletedAt: Date | null = null) => ({ phase, node, result, deletedAt });
const 交付 = () => 项("订单", "尾款结算", "成功交付");
const 线索 = 项("线索", "潜客培育");

describe("序号对字典默认九项（id 不动，名字跟着字典走）", () => {
  it("序号 i = 字典默认第 i 项", () => {
    expect(Object.entries(序).map(([名, i]) => 字典定义.custStatus.默认[i] === 名)).toEqual(Array(9).fill(true));
    expect(客户状态id(6)).toBe("dict-custStatus-6");
  });
});

describe("算客户状态：每一条", () => {
  it("没项目 = null", () => {
    expect(算客户状态([])).toBeNull();
  });

  it("交付个数：1 交付、2 复购、3 和 3 个以上忠诚", () => {
    expect(算客户状态([交付()])).toBe(序.交付);
    expect(算客户状态([交付(), 交付()])).toBe(序.复购);
    expect(算客户状态([交付(), 交付(), 交付()])).toBe(序.忠诚);
    expect(算客户状态([交付(), 交付(), 交付(), 交付()])).toBe(序.忠诚);
  });

  it("异常：订单异常状态", () => {
    expect(算客户状态([项("订单", "物流运输", "异常状态")])).toBe(序.异常);
  });

  it("丢单：商机丢单（停在哪个节点都算，首款支付上丢的也是丢单）", () => {
    expect(算客户状态([项("商机", "共识方案", "丢单")])).toBe(序.丢单);
    expect(算客户状态([项("商机", "首款支付", "丢单")])).toBe(序.丢单);
  });

  it("流失：线索流失", () => {
    expect(算客户状态([项("线索", "线索验证", "线索流失")])).toBe(序.流失);
  });

  it("成交：首款支付，或者进了订单（生产备货到尾款结算）还没结局", () => {
    expect(算客户状态([项("商机", "首款支付")])).toBe(序.成交);
    for (const n of ["生产备货", "物流运输", "安装实施", "验收交付", "尾款结算"]) expect(算客户状态([项("订单", n)])).toBe(序.成交);
  });

  it("意向：进了商机（已转商机 = 商机第一个节点）到签订合同", () => {
    for (const n of ["明确需求", "共识方案", "成交推进", "签约审批", "签订合同"]) expect(算客户状态([项("商机", n)])).toBe(序.意向);
  });

  it("10-31 改名：新名照算；库里旧名（首款支付 / 成功交付）也认", () => {
    expect(算客户状态([项("商机", "首款到账")])).toBe(序.成交);
    expect(算客户状态([项("商机", "首款支付")])).toBe(序.成交);
    expect(算客户状态([项("订单", "交付验收")])).toBe(序.成交);
    expect(算客户状态([项("商机", "痛点挖掘")])).toBe(序.意向);
    expect(算客户状态([项("商机", "合同审批")])).toBe(序.意向);
    expect(算客户状态([项("订单", "尾款结算", "交付结清")])).toBe(序.交付);
    expect(算客户状态([项("订单", "尾款结算", "成功交付"), 项("订单", "尾款结算", "交付结清")])).toBe(序.复购);
    expect(算客户状态([项("订单", "尾款结算", "成功交付"), 项("订单", "尾款结算", "交付结清"), 交付()])).toBe(序.忠诚);
  });

  it("潜在：有项目、都还在线索阶段", () => {
    for (const n of ["潜客培育", "线索验证", "线索推进"]) expect(算客户状态([项("线索", n)])).toBe(序.潜在);
  });
});

describe("算客户状态：先后和混着", () => {
  it("有交付就按交付个数，别的项目异常 / 丢单也不管", () => {
    expect(算客户状态([交付(), 项("订单", "物流运输", "异常状态"), 项("商机", "共识方案", "丢单")])).toBe(序.交付);
    expect(算客户状态([交付(), 交付(), 项("线索", "潜客培育", "线索流失")])).toBe(序.复购);
  });

  it("异常 > 丢单 > 流失（没有在推项目时）；在推的 成交 > 意向 > 潜在", () => {
    const 异常 = 项("订单", "生产备货", "异常状态");
    const 丢单 = 项("商机", "签约审批", "丢单");
    const 流失 = 项("线索", "线索推进", "线索流失");
    const 成交 = 项("商机", "首款支付");
    const 意向 = 项("商机", "明确需求");
    // 都结束了：异常 > 丢单 > 流失
    expect(算客户状态([流失, 丢单, 异常])).toBe(序.异常);
    expect(算客户状态([流失, 丢单])).toBe(序.丢单);
    expect(算客户状态([流失])).toBe(序.流失);
    // 在推的：成交 > 意向 > 潜在
    expect(算客户状态([线索, 意向, 成交])).toBe(序.成交);
    expect(算客户状态([线索, 意向])).toBe(序.意向);
    expect(算客户状态([线索])).toBe(序.潜在);
    // 异常照旧最先（在推的也压不过）；顺序打乱一样
    expect(算客户状态([线索, 意向, 成交, 流失, 丢单, 异常])).toBe(序.异常);
    expect(算客户状态([异常, 线索, 丢单].reverse())).toBe(序.异常);
  });

  it("在推项目优先：有在推的就按在推的定，已结束的丢单 / 流失不压过它", () => {
    const 丢单 = 项("商机", "签约审批", "丢单");
    const 流失 = 项("线索", "线索推进", "线索流失");
    expect(算客户状态([线索, 流失])).toBe(序.潜在);
    expect(算客户状态([项("商机", "明确需求"), 丢单, 流失])).toBe(序.意向);
    expect(算客户状态([项("商机", "首款支付"), 丢单])).toBe(序.成交);
    expect(算客户状态([流失, 项("订单", "物流运输")])).toBe(序.成交);
  });

  it("在推 = 没结局且不在公海：公海里的项目不算在推，丢单 / 流失照旧", () => {
    const 公海的 = { ...线索, pooledAt: new Date() };
    expect(在推(线索)).toBe(true);
    expect(在推(公海的)).toBe(false);
    expect(在推(项("商机", "签约审批", "丢单"))).toBe(false);
    expect(算客户状态([公海的, 项("线索", "线索推进", "线索流失")])).toBe(序.流失);
    // 公海里的项目本身照旧算进状态（只有它一个 = 潜在）
    expect(算客户状态([公海的])).toBe(序.潜在);
  });

  it("不算的（判无效终判「重复线索」）不参与：只剩它 = null；和在推的在一起不影响", () => {
    const 重复 = { ...项("线索", "线索验证", "线索流失"), 不算: true };
    expect(算客户状态([重复])).toBeNull();
    expect(算客户状态([重复, 项("商机", "明确需求")])).toBe(序.意向);
    expect(算客户状态([重复, 项("商机", "签约审批", "丢单")])).toBe(序.丢单);
    expect(算客户状态([重复, 交付()])).toBe(序.交付);
  });

  it("软删的项目不算：删掉的交付、异常都不作数；全删了 = null", () => {
    const 删了 = new Date();
    expect(算客户状态([项("订单", "尾款结算", "成功交付", 删了), 项("商机", "明确需求")])).toBe(序.意向);
    expect(算客户状态([项("订单", "物流运输", "异常状态", 删了), 线索])).toBe(序.潜在);
    expect(算客户状态([交付(), 交付(), 项("订单", "尾款结算", "成功交付", 删了)])).toBe(序.复购);
    expect(算客户状态([项("商机", "首款支付", null, 删了)])).toBeNull();
  });

  it("仅记录用（X-147）：不参与、不算在推；流失线索加一个仅记录用 = 仍是流失", () => {
    const 记录 = { ...线索, source: 仅记录用来源 };
    const 流失 = 项("线索", "线索推进", "线索流失");
    expect(在推(记录)).toBe(false);
    expect(算客户状态([流失, 记录])).toBe(序.流失);
    expect(算客户状态([项("商机", "签约审批", "丢单"), 记录])).toBe(序.丢单);
    expect(算客户状态([项("商机", "明确需求"), 记录])).toBe(序.意向);
    expect(只剩仅记录用([流失, 记录])).toBe(false);
  });

  it("只剩仅记录用 = null（当没有项目），并标 只剩仅记录用（写库不清旧值）；软删 / 重复线索不算的不影响这个判断", () => {
    const 记录 = { ...线索, source: 仅记录用来源 };
    expect(算客户状态([记录])).toBeNull();
    expect(只剩仅记录用([记录])).toBe(true);
    expect(只剩仅记录用([记录, { ...线索, deletedAt: new Date() }])).toBe(true);
    expect(只剩仅记录用([记录, { ...项("线索", "线索验证", "线索流失"), 不算: true }])).toBe(true);
    // 真没有项目不是这一种：照旧 null、照旧清
    expect(只剩仅记录用([])).toBe(false);
    expect(只剩仅记录用([{ ...记录, deletedAt: new Date() }])).toBe(false);
  });

  it("仅记录用推进出潜客培育（或转了商机）：照常算在推", () => {
    const 推了 = { ...项("线索", "线索验证"), source: 仅记录用来源 };
    const 转了 = { ...项("商机", "明确需求"), source: 仅记录用来源 };
    expect(在推(推了)).toBe(true);
    expect(算客户状态([推了])).toBe(序.潜在);
    expect(算客户状态([项("线索", "线索推进", "线索流失"), 推了])).toBe(序.潜在);
    expect(算客户状态([转了])).toBe(序.意向);
    expect(只剩仅记录用([推了])).toBe(false);
  });
});
