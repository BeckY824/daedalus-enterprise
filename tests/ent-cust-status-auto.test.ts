/**
 * 企业版客户状态按项目自动算（10-30，lib/enterprise/cust-status-auto.ts 纯函数）。
 *   - 交付个数：1 交付、2 复购、≥3 忠诚，有交付的不看别的项目
 *   - 没交付：异常 > 丢单 > 流失 > 成交（首款支付 / 进了订单）> 意向（进了商机）> 潜在（都在线索）
 *   - 没项目 = null；软删的项目不算
 */
import { describe, it, expect } from "vitest";
import { 算客户状态, 客户状态序号 as 序, 客户状态id } from "@/lib/enterprise/cust-status-auto";
import { 字典定义 } from "@/lib/enterprise/dict-kinds";

const 项 = (phase: string, node: string, result: string | null = null, deletedAt: Date | null = null) => ({ phase, node, result, deletedAt });
const 交付 = () => 项("订单", "尾款结算", "成功交付");
const 线索 = 项("线索", "潜客培育");

describe("序号对字典默认九项（id 不动，名字跟着字典走）", () => {
  it("序号 i = 字典默认第 i 项", () => {
    expect(Object.entries(序).map(([名, i]) => 字典定义.custStatus.默认[i] === 名)).toEqual(Array(9).fill(true));
    expect(客户状态id(6)).toBe("dict-custStatus-6");
  });
});

describe("算客户状态：每一条", () => {
  it("没项目 = null", () => {
    expect(算客户状态([])).toBeNull();
  });

  it("交付个数：1 交付、2 复购、3 和 3 个以上忠诚", () => {
    expect(算客户状态([交付()])).toBe(序.交付);
    expect(算客户状态([交付(), 交付()])).toBe(序.复购);
    expect(算客户状态([交付(), 交付(), 交付()])).toBe(序.忠诚);
    expect(算客户状态([交付(), 交付(), 交付(), 交付()])).toBe(序.忠诚);
  });

  it("异常：订单异常状态", () => {
    expect(算客户状态([项("订单", "物流运输", "异常状态")])).toBe(序.异常);
  });

  it("丢单：商机丢单（停在哪个节点都算，首款支付上丢的也是丢单）", () => {
    expect(算客户状态([项("商机", "共识方案", "丢单")])).toBe(序.丢单);
    expect(算客户状态([项("商机", "首款支付", "丢单")])).toBe(序.丢单);
  });

  it("流失：线索流失", () => {
    expect(算客户状态([项("线索", "线索验证", "线索流失")])).toBe(序.流失);
  });

  it("成交：首款支付，或者进了订单（生产备货到尾款结算）还没结局", () => {
    expect(算客户状态([项("商机", "首款支付")])).toBe(序.成交);
    for (const n of ["生产备货", "物流运输", "安装实施", "验收交付", "尾款结算"]) expect(算客户状态([项("订单", n)])).toBe(序.成交);
  });

  it("意向：进了商机（已转商机 = 商机第一个节点）到签订合同", () => {
    for (const n of ["明确需求", "共识方案", "成交推进", "签约审批", "签订合同"]) expect(算客户状态([项("商机", n)])).toBe(序.意向);
  });

  it("潜在：有项目、都还在线索阶段", () => {
    for (const n of ["潜客培育", "线索验证", "线索推进"]) expect(算客户状态([项("线索", n)])).toBe(序.潜在);
  });
});

describe("算客户状态：先后和混着", () => {
  it("有交付就按交付个数，别的项目异常 / 丢单也不管", () => {
    expect(算客户状态([交付(), 项("订单", "物流运输", "异常状态"), 项("商机", "共识方案", "丢单")])).toBe(序.交付);
    expect(算客户状态([交付(), 交付(), 项("线索", "潜客培育", "线索流失")])).toBe(序.复购);
  });

  it("异常 > 丢单 > 流失 > 成交 > 意向 > 潜在", () => {
    const 异常 = 项("订单", "生产备货", "异常状态");
    const 丢单 = 项("商机", "签约审批", "丢单");
    const 流失 = 项("线索", "线索推进", "线索流失");
    const 成交 = 项("商机", "首款支付");
    const 意向 = 项("商机", "明确需求");
    const 全 = [线索, 意向, 成交, 流失, 丢单, 异常];
    expect(算客户状态(全)).toBe(序.异常);
    expect(算客户状态(全.slice(0, 5))).toBe(序.丢单);
    expect(算客户状态(全.slice(0, 4))).toBe(序.流失);
    expect(算客户状态(全.slice(0, 3))).toBe(序.成交);
    expect(算客户状态(全.slice(0, 2))).toBe(序.意向);
    expect(算客户状态(全.slice(0, 1))).toBe(序.潜在);
    // 顺序打乱一样
    expect(算客户状态([异常, 线索, 丢单].reverse())).toBe(序.异常);
    expect(算客户状态([意向, 流失, 线索])).toBe(序.流失);
  });

  it("软删的项目不算：删掉的交付、异常都不作数；全删了 = null", () => {
    const 删了 = new Date();
    expect(算客户状态([项("订单", "尾款结算", "成功交付", 删了), 项("商机", "明确需求")])).toBe(序.意向);
    expect(算客户状态([项("订单", "物流运输", "异常状态", 删了), 线索])).toBe(序.潜在);
    expect(算客户状态([交付(), 交付(), 项("订单", "尾款结算", "成功交付", 删了)])).toBe(序.复购);
    expect(算客户状态([项("商机", "首款支付", null, 删了)])).toBeNull();
  });
});
