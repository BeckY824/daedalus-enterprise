describe("换负责人归零上限（12 个月内转让满 2 次，第 3 次起不归零）", () => {
  it("第 3 次转让不归零；离职交接计次；捞取、公海指派、市场首次分配不计次且归零", () => {
    const 两次 = [{ 日: 日(10), 方式: "转让" as const }, { 日: 日(40), 方式: "离职交接" as const }];
    expect(换负责人归零(两次, { 日: 日(70), 方式: "转让" }, 规则)).toBe(false);
    expect(换负责人归零(两次.slice(0, 1), { 日: 日(70), 方式: "转让" }, 规则)).toBe(true);
    expect(换负责人归零(两次, { 日: 日(70), 方式: "公海捞取" }, 规则)).toBe(true);
    // 中间夹着捞取 / 指派 / 市场首次分配不占次数
    const 夹 = [{ 日: 日(5), 方式: "市场首次分配" as const }, { 日: 日(10), 方式: "转让" as const }, { 日: 日(20), 方式: "公海捞取" as const }, { 日: 日(25), 方式: "公海指派" as const }];
    expect(换负责人归零(夹, { 日: 日(70), 方式: "转让" }, 规则)).toBe(true);
    // 窗口外的不算：第一次转让在 12 个月以前
    expect(换负责人归零([{ 日: "2026-11-10", 方式: "转让" }, { 日: "2027-03-01", 方式: "转让" }], { 日: "2027-11-11", 方式: "转让" }, 规则)).toBe(true);
    expect(换负责人归零([{ 日: "2026-11-11", 方式: "转让" }, { 日: "2027-03-01", 方式: "转让" }], { 日: "2027-11-10", 方式: "转让" }, 规则)).toBe(false);
    // 上限改成 3 次：第 3 次又归零
    expect(换负责人归零(两次, { 日: 日(70), 方式: "转让" }, { 转让归零: { 次数: 3, 窗口月数: 12 } })).toBe(true);
  });

  it("算三态里：第 3 次转让不拨钟，钟从第 2 次接着走；捞取照样拨", () => {
    const 三次 = [{ 日: 日(10), 方式: "转让" as const }, { 日: 日(40), 方式: "转让" as const }, { 日: 日(100), 方式: "转让" as const }];
    expect(当天(131, { 换负责人们: 三次 })).toMatchObject({ 归零日: 日(40), 状态: "沉睡", 算数换负责人日: 日(40) });
    expect(当天(131, { 换负责人们: [...三次, { 日: 日(120), 方式: "公海捞取" }] })).toMatchObject({ 归零日: 日(120), 状态: "活跃" });
    // 转让当时存下的「归零」优先（规则后改不回改历史）
    expect(当天(131, { 换负责人们: [三次[0], 三次[1], { ...三次[2], 归零: true }] }).归零日).toBe(日(100));
  });

  it("加月：月底按那个月最后一天", () => {
    expect(加月("2027-03-31", -1)).toBe("2027-02-28");
    expect(加月("2027-11-10", -12)).toBe("2026-11-10");
  });
});

describe("继续持有（推后 30 天、钟不拨零、各轮一次、累计 3 次 / 合计 90 天）", () => {
  it("沉睡轮点一次：三个节点一起顺延 30 天，又回到活跃；同一轮不能再点", () => {
    const f = { 推后们: [{ 日: 日(95), 轮: "沉睡" as const, 天数: 30 }] };
    expect(当天(100, f)).toMatchObject({ 状态: "活跃", 基准日: 日(30), 节点: { 沉睡: 日(120), 待回收: 日(210), 进公海: 日(240) }, 继续持有: { 已用次数: 1, 已用天数: 30, 剩次数: 2, 剩天数: 60, 能推: false } });
    const r = 当天(125, f);
    expect(r.状态).toBe("沉睡");
    expect(r.继续持有).toMatchObject({ 能推: false, 不能原因: "沉睡这一轮已经继续持有过一次" });
    expect(当天(210, f).状态).toBe("待回收");
    expect(当天(210, f).继续持有.能推).toBe(true);
  });

  it("活跃、该进公海时不能点", () => {
    expect(当天(10).继续持有).toMatchObject({ 能推: false, 不能原因: "只有沉睡、待回收时能继续持有", 剩次数: 3, 剩天数: 90 });
    expect(当天(215, 按时(180, 999)).继续持有.能推).toBe(false);
  });

  it("第 4 次被拒：两轮钟用掉 3 次（换负责人拨了钟、额度接着用），第二轮钟的待回收轮点不了", () => {
    const g = { ...规则, 继续持有: { 每次天数: 30, 累计次数: 3, 累计天数: 300 } };
    const 推后们 = [
      { 日: 日(95), 轮: "沉睡" as const, 天数: 30 },
      { 日: 日(215), 轮: "待回收" as const, 天数: 30 },
      { 日: 日(350), 轮: "沉睡" as const, 天数: 30, 代选: true },
    ];
    const f = { 推后们, 换负责人们: [{ 日: 日(250), 方式: "转让" as const }] };
    // 第 250 天转让拨钟：本钟只算 350 那次；第 250+90+30 = 370 天起沉睡，250+180+30 = 460 天起待回收
    const r = 当天(460, f, g);
    expect(r).toMatchObject({ 状态: "待回收", 归零日: 日(250), 基准日: 日(280) });
    expect(r.继续持有).toMatchObject({ 已用次数: 3, 剩次数: 0, 能推: false, 不能原因: "继续持有已用满 3 次" });
  });

  it("合计天数先于次数拦住：每次推后 45 天、合计 90 → 用了 2 次就点不了（次数还剩 1）；每次 15 天时合计永远拦不住，靠次数拦", () => {
    const g45 = { ...规则, 继续持有: { 每次天数: 45, 累计次数: 3, 累计天数: 90 } };
    const 两次 = [{ 日: 日(95), 轮: "沉睡" as const, 天数: 45 }, { 日: 日(230), 轮: "待回收" as const, 天数: 45 }];
    const f = { 推后们: 两次, 换负责人们: [{ 日: 日(260), 方式: "转让" as const }] };
    expect(当天(355, f, g45).继续持有).toMatchObject({ 已用次数: 2, 剩次数: 1, 已用天数: 90, 剩天数: 0, 能推: false, 不能原因: "继续持有合计最多顺延 90 天，已顺延 90 天" });
    const g15 = { ...规则, 继续持有: { 每次天数: 15, 累计次数: 3, 累计天数: 90 } };
    const 三次 = [...两次.map((x) => ({ ...x, 天数: 15 })), { 日: 日(355), 轮: "沉睡" as const, 天数: 15 }];
    expect(当天(470, { ...f, 推后们: 三次 }, g15).继续持有).toMatchObject({ 已用次数: 3, 已用天数: 45, 剩天数: 45, 能推: false, 不能原因: "继续持有已用满 3 次" });
  });

  it("记一条有内容的沟通：额度重置（次数、天数清零）、钟归零；同一天两条沟通也只是一次重置", () => {
    const 推后们 = [{ 日: 日(95), 轮: "沉睡" as const, 天数: 30 }, { 日: 日(215), 轮: "待回收" as const, 天数: 30 }];
    const r = 当天(320, { 推后们, 最近沟通日: 日(230) });
    expect(r).toMatchObject({ 归零日: 日(230), 基准日: 日(230), 状态: "沉睡", 继续持有: { 已用次数: 0, 已用天数: 0, 剩次数: 3, 剩天数: 90, 能推: true } });
    // 同一天两条沟通：调用方只传「最近有内容沟通日」，额度满 3 次，不会变成 6 次
    const 再 = 当天(320, { 推后们: [...推后们, { 日: 日(230), 轮: "沉睡", 天数: 30 }], 最近沟通日: 日(230) });
    expect(再.继续持有).toMatchObject({ 已用次数: 0, 剩次数: 3 });
  });

  it("换负责人不重置额度（钟归零，用过的次数接着算）；项目推进也不重置额度", () => {
    const 推后们 = [{ 日: 日(95), 轮: "沉睡" as const, 天数: 30 }];
    expect(当天(240, { 推后们, 换负责人们: [{ 日: 日(140), 方式: "转让" }] })).toMatchObject({ 归零日: 日(140), 状态: "沉睡", 继续持有: { 已用次数: 1, 剩次数: 2, 能推: true } });
    expect(当天(240, { 推后们, 最近推进日: 日(140) }).继续持有).toMatchObject({ 已用次数: 1, 剩天数: 60 });
  });
});

