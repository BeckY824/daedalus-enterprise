/**
 * 客户三态计时（lib/enterprise/tri-state.ts，纯函数）：推演稿 S1–S7、边界日、成交客户、换负责人归零上限、继续持有额度、跨线取较长、改天数跟着变。
 * 「第 N 天」都从 2026-11-01（系统起算日）数，除非另说。
 */
import { describe, it, expect } from "vitest";
import { 算三态, 换负责人归零, 成交条件满足, 加天, 加月, type 三态事实, type 三态结果, type 三态项目 } from "@/lib/enterprise/tri-state";
import { 默认三态规则, type 三态规则 } from "@/lib/project/org-rules";

const 起 = "2026-11-01";
const 日 = (n: number) => 加天(起, n);
const 规则: 三态规则 = { ...默认三态规则, 开: true };
const 事实 = (改: Partial<三态事实> = {}): 三态事实 => ({
  有负责人: true, 在公海: false, 已删: false, 无效: false, 负责人是市场: false,
  最近沟通日: null, 最近推进日: null, 导入完成日: null,
  项目们: [], 成交成立日: null, 推后们: [], 换负责人们: [], 本轮待回收提醒次数: 0, 本轮最近待回收提醒日: null,
  ...改,
});
const 计时 = (r: 三态结果) => {
  if (!r.计时) throw new Error(`不计时：${r.原因}`);
  return r;
};
const 当天 = (n: number, f: Partial<三态事实> = {}, g: 三态规则 = 规则) => 计时(算三态(事实(f), g, 日(n)));
/** 待回收提醒都按时发了：第 R 天进待回收，到第 n 天（不含当天）已经发了几次、最近一次哪天 */
const 按时 = (R: number, n: number, 间隔 = 10) => {
  const 发过 = [0, 间隔, 2 * 间隔].filter((o) => R + o < n);
  return { 本轮待回收提醒次数: 发过.length, 本轮最近待回收提醒日: 发过.length ? 日(R + 发过[发过.length - 1]) : null };
};
const 内贸项 = (改: Partial<三态项目> = {}): 三态项目 => ({ 阶段: "商机", 结束: false, 业务线: "内贸", ...改 });

describe("边界日（普通客户 90 / 180 / +30）", () => {
  it("状态、距下一节点、提醒按天走", () => {
    const 看 = (n: number) => { const r = 当天(n, 按时(180, n)); return [r.状态, r.距下一节点, r.提醒?.事由 ?? null, r.提醒?.主送 ?? null, r.提醒?.抄送 ?? null]; };
    expect(看(0)).toEqual(["活跃", 90, null, null, null]);
    expect(看(89)).toEqual(["活跃", 1, null, null, null]);
    expect(看(90)).toEqual(["沉睡", 90, "进入沉睡", ["本人"], []]);
    expect(看(92)).toEqual(["沉睡", 88, "沉睡周提醒", ["本人"], []]); // 2027-02-01 周一
    expect(看(119)).toEqual(["沉睡", 61, null, null, null]);
    expect(看(120)).toEqual(["沉睡", 60, "沉睡抄上级", ["本人", "直属上级"], []]);
    expect(看(127)).toEqual(["沉睡", 53, "沉睡周提醒", ["本人", "直属上级"], []]); // 周一，已带上级
    expect(看(179)).toEqual(["沉睡", 1, null, null, null]);
    expect(看(180)).toEqual(["待回收", 30, "待回收提醒", ["条线总管理"], ["本人", "直属上级"]]);
    expect(看(189)).toEqual(["待回收", 21, null, null, null]);
    expect(看(190)).toEqual(["待回收", 20, "待回收提醒", ["条线总管理"], ["本人", "直属上级"]]);
    expect(看(200)).toEqual(["待回收", 10, "待回收提醒", ["条线总管理"], ["本人", "直属上级"]]);
    expect(看(209)).toEqual(["待回收", 1, null, null, null]);
    expect(看(210)).toEqual(["该进公海", null, null, null, null]);
    expect([180, 190, 200].map((n) => 当天(n, 按时(180, n)).提醒?.第几次)).toEqual([1, 2, 3]);
    expect(当天(210, 按时(180, 210)).最早进公海日).toBe("2027-05-30");
    expect(当天(210).节点).toEqual({ 沉睡: "2027-01-30", 待回收: "2027-04-30", 进公海: "2027-05-30" });
  });
});

describe("成交客户（只换活跃段 365，后两段共用内贸那套间隔：455 / 485）", () => {
  const 成交 = { 成交成立日: "2026-10-01", 项目们: [内贸项({ 阶段: "订单", 结束: true })] };
  it("364 / 365 / 454 / 455 / 484 / 485", () => {
    const 看 = (n: number) => { const r = 当天(n, { ...成交, ...按时(455, n) }); return [r.状态, r.提醒?.事由 ?? null]; };
    expect(看(364)).toEqual(["活跃", null]);
    expect(看(365)).toEqual(["沉睡", "进入沉睡"]);
    expect(看(395)).toEqual(["沉睡", "沉睡抄上级"]);
    expect(看(454)).toEqual(["沉睡", null]);
    expect(看(455)).toEqual(["待回收", "待回收提醒"]);
    expect(看(484)).toEqual(["待回收", null]);
    expect(看(485)).toEqual(["该进公海", null]);
    expect(当天(0, 成交)).toMatchObject({ 按成交算: true, 成交首次成立: false, 节点天: { 沉睡: 365, 待回收: 455, 进公海: 485 } });
    expect([465, 475].map((n) => 当天(n, { ...成交, ...按时(455, n) }).提醒?.第几次)).toEqual([2, 3]);
  });

  it("改了普通客户的沉睡→待回收间隔，成交客户的待回收日跟着变；改活跃段只挪活跃段", () => {
    const 改 = { ...规则, 内贸: { 沉睡: 60, 待回收: 180, 进公海: 40 } };
    expect(当天(0, 成交, 改).节点天).toEqual({ 沉睡: 365, 待回收: 485, 进公海: 525 });
    expect(当天(0, 成交, { ...规则, 成交: { 活跃段: 300 } }).节点天).toEqual({ 沉睡: 300, 待回收: 390, 进公海: 420 });
  });

  it("成交首次成立：订单阶段结束过、且没有项目还没结束；只有丢单 / 线索流失的不算；成立后项目重启或新增不掉回普通天数", () => {
    expect(成交条件满足([内贸项({ 阶段: "订单", 结束: true })])).toBe(true);
    expect(成交条件满足([内贸项({ 阶段: "订单", 结束: true }), 内贸项()])).toBe(false);
    expect(成交条件满足([内贸项({ 阶段: "商机", 结束: true }), 内贸项({ 阶段: "线索", 结束: true })])).toBe(false);
    expect(成交条件满足([])).toBe(false);
    // 还没存成立日、今天满足 → 首次成立，按成交算
    expect(当天(100, { 项目们: [内贸项({ 阶段: "订单", 结束: true })] })).toMatchObject({ 成交首次成立: true, 按成交算: true, 状态: "活跃" });
    // 成立过了：之后新开了商机项目（没结束），仍按 365 算、不再报首次成立
    expect(当天(100, { 成交成立日: 日(10), 项目们: [内贸项({ 阶段: "订单", 结束: true }), 内贸项()] })).toMatchObject({ 成交首次成立: false, 按成交算: true, 状态: "活跃" });
    // 没成立、名下还有项目在推：普通天数
    expect(当天(100, { 项目们: [内贸项({ 阶段: "订单", 结束: true }), 内贸项()] })).toMatchObject({ 按成交算: false, 状态: "沉睡" });
  });
});

describe("推演稿 S1–S7（推荐方案：钟挂客户）", () => {
  it("S1 一个客户 5 个项目只跟 1 个：甲每月有沟通，乙–戊没人动 → 客户一直活跃", () => {
    const 项目们 = [内贸项(), 内贸项({ 阶段: "线索" }), 内贸项(), 内贸项({ 阶段: "线索" }), 内贸项()];
    for (const n of [90, 150, 210, 300]) {
      const r = 当天(n, { 项目们, 最近沟通日: 日(n - 20) });
      expect([r.状态, r.提醒]).toEqual(["活跃", null]);
    }
  });

  it("S2 多联系人只和 1 个在聊：沟通只刷客户，客户活跃，不提醒", () => {
    expect(当天(200, { 最近沟通日: 日(150) })).toMatchObject({ 状态: "活跃", 提醒: null, 归零日: 日(150), 距下一节点: 40 });
  });

  it("S3 第 80 天离职交接给新人：接手当天归零，新人从接手起第 90 天才沉睡", () => {
    const f = { 换负责人们: [{ 日: 日(80), 方式: "离职交接" as const }] };
    expect(当天(89, f).状态).toBe("活跃");
    expect(当天(169, f).状态).toBe("活跃");
    expect(当天(170, f)).toMatchObject({ 状态: "沉睡", 提醒: { 事由: "进入沉睡", 主送: ["本人"] } });
  });

  it("S4 第 210 天进公海、10 天后被捞：公海里不计时；捞取当天归零、不占转让次数", () => {
    expect(算三态(事实({ 有负责人: false, 在公海: true }), 规则, 日(215))).toEqual({ 计时: false, 原因: "没负责人", 成交首次成立: false });
    const f = { 换负责人们: [{ 日: 日(220), 方式: "公海捞取" as const }] };
    expect(当天(220, f)).toMatchObject({ 状态: "活跃", 归零日: 日(220), 距下一节点: 90 });
    expect(当天(310, f).状态).toBe("沉睡");
  });

  it("S5 外贸单设 120 / 240：只有外贸项目用外贸那套；内外贸都有取较长的；没项目 / 暂不分配用内贸", () => {
    const g = { ...规则, 外贸: { 沉睡: 120, 待回收: 240, 进公海: 30 } };
    const 外 = 内贸项({ 业务线: "外贸" });
    expect(当天(100, { 项目们: [外] }, g)).toMatchObject({ 套: "外贸", 状态: "活跃", 节点天: { 沉睡: 120, 待回收: 240, 进公海: 270 } });
    expect(当天(100, { 项目们: [外, 内贸项({ 业务线: "暂不分配" })] }, g).套).toBe("外贸");
    expect(当天(100, { 项目们: [外, 内贸项()] }, g).套).toBe("外贸");
    expect(当天(100, { 项目们: [内贸项({ 业务线: "暂不分配" })] }, g)).toMatchObject({ 套: "内贸", 状态: "沉睡" });
    expect(当天(100, {}, g).套).toBe("内贸");
  });

  it("S6 同事在推项目：同事推节点拨客户的钟；同事项目冷了、到第 210 天进不去公海 → 被挡，只推总管理、每 30 天一次", () => {
    const 同事项 = 内贸项({ 同事负责: true });
    expect(当天(200, { 项目们: [同事项], 最近推进日: 日(150) }).状态).toBe("活跃");
    const f = { 项目们: [同事项], ...按时(180, 999) };
    expect(当天(210, f)).toMatchObject({ 状态: "该进公海", 被挡: true, 提醒: { 事由: "被挡请裁决", 主送: ["条线总管理"], 抄送: [] } });
    expect(当天(225, f).提醒).toBeNull();
    expect(当天(240, f).提醒?.事由).toBe("被挡请裁决");
    // 第 245 天总管理裁决「暂缓回收」：30 天内不再推，第 275 天再推
    const 暂缓 = { ...f, 暂缓回收日: 日(245) };
    expect(当天(245, 暂缓).提醒).toBeNull();
    expect(当天(270, 暂缓).提醒).toBeNull();
    expect(当天(275, 暂缓).提醒?.事由).toBe("被挡请裁决");
    // 没同事项目挡着：照常该进公海，不发被挡提醒（自动进公海的通知调用方发）
    expect(当天(210, 按时(180, 999))).toMatchObject({ 状态: "该进公海", 被挡: false, 提醒: null });
  });

  it("S7 成交后转售后：订单阶段没结束时一律活跃、钟不走；结束后按成交 365 计，售后记沟通拨零", () => {
    expect(当天(400, { 项目们: [内贸项({ 阶段: "订单" })] })).toMatchObject({ 状态: "活跃", 订单在推: true, 下一节点: null, 距下一节点: null, 提醒: null, 按成交算: false });
    const 成交 = { 成交成立日: 日(30), 项目们: [内贸项({ 阶段: "订单", 结束: true })] };
    expect(当天(400, 成交).状态).toBe("沉睡");
    expect(当天(400, { ...成交, 最近沟通日: 日(380) })).toMatchObject({ 状态: "活跃", 距下一节点: 345 });
  });
});

