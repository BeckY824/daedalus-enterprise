/**
 * 占位假号判定（M-导入-36、P-全局-06）：全同数字、连续 0、顺序数字。导入去掉、表单拦下共用这一个函数。
 * 号码全是编造的
 */
import { describe, expect, it } from "vitest";
import { 是占位号, 占位号提示 } from "@/lib/placeholder-phone";

describe("是占位号", () => {
  it("全同数字（含 +86、空格横杠）算占位", () => {
    for (const v of ["11111111111", "00000000", "+86 111 1111 1111", "0086-11111111111", "8888-8888", "99999"]) expect(是占位号(v), v).toBe(true);
  });

  it("连续 0：短前缀后面跟 7 个以上 0 算占位", () => {
    for (const v of ["13800000000", "10000000000", "021-0000000", "+86 13900000000"]) expect(是占位号(v), v).toBe(true);
  });

  it("顺序数字（升、降，9 接 0）算占位", () => {
    for (const v of ["12345", "123456789", "1234567890", "0123456789", "987654321", "54321"]) expect(是占位号(v), v).toBe(true);
  });

  it("真号、中间夹着 0 的号、带字母的、太短的、空的都不算", () => {
    for (const v of ["13900000001", "13800001111", "021-5555-0101", "+1 415 555 0101", "wxid_111111", "1111", "123", "", null, undefined, "13812345678"]) {
      expect(是占位号(v), String(v)).toBe(false);
    }
  });

  it("带分机的看主号", () => {
    expect(是占位号("00000000转801")).toBe(true);
    expect(是占位号("01012345678转801")).toBe(false);
  });

  it("提示叫人填真实号码", () => {
    expect(占位号提示("电话")).toContain("真实号码");
    expect(占位号提示("电话")).toContain("电话");
  });
});
