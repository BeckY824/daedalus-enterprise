/**
 * 注册 / 留资的「每天几次」按北京日切（rate-limit.ts 日计数 走 business-clock beijingDay）：
 * 原来取 UTC 日，北京 0–8 点还算前一天、北京早上 8 点才翻篇。宿主 TZ 是伦敦也按北京数
 */
import { afterEach, beforeEach, describe, expect, it } from "vitest";
import { 今日计数, 记一次今日, 今日注册数, 记一次注册, 重置注册计数 } from "@/lib/rate-limit";

const 原TZ = process.env.TZ;
beforeEach(() => {
  重置注册计数();
  process.env.TZ = "Europe/London";
});
afterEach(() => {
  重置注册计数();
  if (原TZ === undefined) delete process.env.TZ;
  else process.env.TZ = 原TZ;
});

describe("日计数按北京日切", () => {
  it("UTC 16:00 前后跨北京零点：之前记的算昨天，之后从 0 数", () => {
    const 北京昨晚 = new Date("2026-11-25T15:59:59.000Z"); // 北京 11-25 23:59:59
    const 北京零点 = new Date("2026-11-25T16:00:00.000Z"); // 北京 11-26 00:00
    记一次注册("203.0.113.7", 北京昨晚);
    记一次注册("203.0.113.7", 北京昨晚);
    expect(今日注册数("203.0.113.7", 北京昨晚)).toBe(2);
    expect(今日注册数("203.0.113.7", 北京零点)).toBe(0);
    记一次注册("203.0.113.7", 北京零点);
    expect(今日注册数("203.0.113.7", 北京零点)).toBe(1);
  });

  it("伦敦 / UTC 零点前后（北京早上 8 点）是北京同一天：不清零", () => {
    const 伦敦晚上 = new Date("2026-11-25T23:59:00.000Z"); // 北京 11-26 07:59
    const 伦敦零点后 = new Date("2026-11-26T00:01:00.000Z"); // 北京 11-26 08:01
    记一次今日("lead:198.51.100.9", 伦敦晚上);
    expect(今日计数("lead:198.51.100.9", 伦敦零点后)).toBe(1);
    记一次今日("lead:198.51.100.9", 伦敦零点后);
    expect(今日计数("lead:198.51.100.9", 伦敦零点后)).toBe(2);
    // 北京下一个零点（UTC 11-26 16:00）才翻篇
    expect(今日计数("lead:198.51.100.9", new Date("2026-11-26T15:59:59.000Z"))).toBe(2);
    expect(今日计数("lead:198.51.100.9", new Date("2026-11-26T16:00:00.000Z"))).toBe(0);
  });

  it("夏令时的伦敦（UTC+1）也按北京数", () => {
    const 前 = new Date("2026-07-01T15:30:00.000Z"); // 伦敦 16:30、北京 23:30
    const 后 = new Date("2026-07-01T16:30:00.000Z"); // 伦敦 17:30、北京 07-02 00:30
    记一次注册("192.0.2.1", 前);
    expect(今日注册数("192.0.2.1", 前)).toBe(1);
    expect(今日注册数("192.0.2.1", 后)).toBe(0);
  });
});
