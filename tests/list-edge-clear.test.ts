/**
 * 列表横滚停在最左时，表头别被钉住的操作列 + 渐隐压成半截（设计语言 C-A2 · C-新6）：补宽量怎么取。
 * 界 = 操作列左沿，渐隐 24；字 = 各表头字左右沿（不补时）
 */
import { expect, it } from "vitest";
import { 躲开钉住列补宽 } from "@/lib/list-edge-clear";

const 界 = 1000, 渐隐 = 24, 上限 = 160;

it("没有压着的：不补", () => {
  expect(躲开钉住列补宽([{ 左: 800, 右: 900 }, { 左: 1010, 右: 1060 }], 界, 渐隐, 上限)).toBe(0);
});

it("一个表头跨在渐隐 / 操作列上：把它整个推到操作列底下，前一个还在渐隐左边", () => {
  // 1366 实操：关联订单 1183–1236、操作列 1216 → 换成相对坐标
  const d = 躲开钉住列补宽([{ 左: 860, 右: 930 }, { 左: 967, 右: 1020 }], 界, 渐隐, 上限);
  expect(d).toBe(33);
  expect(930 + d).toBeLessThanOrEqual(界 - 渐隐);
  expect(967 + d).toBeGreaterThanOrEqual(界);
});

it("推了一个、前一个又掉进渐隐：再往前退一个", () => {
  // 推第二个要 40，第一个右沿 950 + 40 = 990 > 976；只能连第一个一起推走（推 100）
  expect(躲开钉住列补宽([{ 左: 900, 右: 950 }, { 左: 960, 右: 1010 }], 界, 渐隐, 上限)).toBe(100);
});

it("要补的超过上限：不补（免得名字后面推出一大片空）", () => {
  expect(躲开钉住列补宽([{ 左: 700, 右: 990 }], 界, 渐隐, 上限)).toBe(0);
});
