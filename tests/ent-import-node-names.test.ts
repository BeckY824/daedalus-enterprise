/**
 * 导入时 1.0 叫法 → 2.0 节点（10-27 会上对方确认的对照表，一条不多一条不少）。
 *   企业版 10-31 改名：对到的是新名（痛点挖掘 / 方案确认 / 交付验收 / 交付结清）；表里写 2.0 旧名的也认成新名
 *   表里的每个 1.0 叫法都换到对照表那一格；2.0 自己的节点和结局原样；认不出的给 null（后面问 AI）
 */
import { describe, expect, it } from "vitest";
import { 项目节点对值, 项目阶段值 } from "@/lib/enterprise-import/project-values";

const 对照表: [string[], string][] = [
  [["市场验证", "市场培育", "线索分配"], "潜客培育"],
  [["市场复审"], "线索验证"],
  [["线索培育"], "线索推进"],
  [["已转商机", "正式立项"], "痛点挖掘"],
  [["流失回访"], "线索流失"],
  [["解决方案"], "方案确认"],
  [["商机赢单", "赢单", "赢单成交", "备货安装"], "生产备货"],
  [["商机丢单", "项目丢单", "丢单回访", "输单"], "丢单"],
  [["交付验收"], "交付验收"],
  [["项目交付", "后售培育"], "交付结清"],
];

describe("1.0 叫法对到 2.0", () => {
  it.each(对照表)("%j → %s", (旧, 新) => {
    for (const s of 旧) expect(项目节点对值(s)).toBe(新);
    expect(项目阶段值).toContain(新);
  });

  it("两头的空格不碍事；2.0 的节点和结局原样；认不出的给 null", () => {
    expect(项目节点对值(" 市场复审 ")).toBe("线索验证");
    for (const s of 项目阶段值) expect(项目节点对值(s)).toBe(s);
    expect(项目节点对值("随便写的")).toBeNull();
    // 2.0 旧名（改名前的叫法）认成新名
    for (const [旧, 新] of [["明确需求", "痛点挖掘"], ["共识方案", "方案确认"], ["签约审批", "合同审批"], ["首款支付", "首款到账"], ["验收交付", "交付验收"], ["成功交付", "交付结清"]]) expect(项目节点对值(旧)).toBe(新);
    for (const 旧 of ["明确需求", "共识方案", "签约审批", "首款支付", "验收交付", "成功交付"]) expect(项目阶段值).not.toContain(旧);
  });
});
