/**
 * 开持有上限前的预览人数（lib/project/org-rules.ts 到上限的人数，10-30 设置页开关）：
 *   照存着的默认 / 每人上限算，手上 >= 上限的算到了；不限（999）的不算；没数到的人当 0 个
 */
import { describe, it, expect } from "vitest";
import { 到上限的人数, 默认组织规则 } from "@/lib/project/org-rules";

describe("到上限的人数", () => {
  const 公海 = { ...默认组织规则.公海, 默认上限: 20, 每人上限: { b: 5, c: 999, d: 0 } };
  it("默认、单独设、不限、0 个都按各自的算", () => {
    // a 20/20 到了；b 6/5 超了；c 不限不算；d 上限 0 手上没有也算到了；e 19/20 没到
    expect(到上限的人数(公海, { a: 20, b: 6, c: 100, e: 19 }, ["a", "b", "c", "d", "e"])).toBe(3);
  });
  it("只数给的人", () => {
    expect(到上限的人数(公海, { a: 30 }, ["e"])).toBe(0);
  });
});
