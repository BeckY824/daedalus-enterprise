/**
 * 复盘「沟通」时间线按天分组（前端改版逐块确认 ov.talk）：今天 / 昨天 / 今年别的日子「M-D」/ 往年「YYYY-M-D」。
 * 行已经是时间倒序（服务端排好），分组只是按顺序切段，组里不重排。
 */
import { describe, expect, it } from "vitest";
import { dayjs } from "@/lib/utils";
import { 沟通按天 } from "@/lib/project/talk-days";

const 今 = dayjs("2026-11-15T15:00:00");
const 行 = (id: string, 时间: string) => ({ id, 时间 });

describe("沟通按天", () => {
  it("今天、昨天、今年、往年各叫各的；顺序照原样", () => {
    const g = 沟通按天([行("a", "2026-11-15T09:00:00"), 行("b", "2026-11-15T08:00:00"), 行("c", "2026-11-14T23:59:00"), 行("d", "2026-11-03T10:00:00"), 行("e", "2025-12-31T10:00:00")], 今);
    expect(g.map((x) => [x.叫法, x.行.map((r) => r.id).join("")])).toEqual([["今天", "ab"], ["昨天", "c"], ["11-3", "d"], ["2025-12-31", "e"]]);
  });
  it("没有行 → 没有组；同一天隔开（服务端排好的不会，但也不合并）", () => {
    expect(沟通按天([], 今)).toEqual([]);
    const g = 沟通按天([行("a", "2026-11-10T09:00:00"), 行("b", "2026-11-09T09:00:00"), 行("c", "2026-11-10T08:00:00")], 今);
    expect(g.map((x) => x.叫法)).toEqual(["11-10", "11-9", "11-10"]);
    expect(new Set(g.map((x) => x.键)).size).toBe(3);
  });
});
