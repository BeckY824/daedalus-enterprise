/**
 * 窄格金额缩写（设计语言 D39，C-A1 渠道看板 KPI）：不到 1 万原样；1 万～1,000 万一位小数「万」；1,000 万～1 亿取整「万」；1 亿起两位小数「亿」。
 * 不换汇，多币种「 · 」连；全值另用 合计文字（悬停）。
 */
import { describe, expect, it } from "vitest";
import { 金额缩写, 合计缩写, 合计文字 } from "@/lib/currency";

describe("金额缩写", () => {
  it("档位和取法", () => {
    expect(金额缩写(8600)).toBe("¥ 8,600");
    expect(金额缩写(12000)).toBe("¥ 1.2 万");
    expect(金额缩写(10000)).toBe("¥ 1 万");
    expect(金额缩写(5326000)).toBe("¥ 532.6 万");
    expect(金额缩写(9999999)).toBe("¥ 1,000 万");
    expect(金额缩写(12800000)).toBe("¥ 1,280 万");
    expect(金额缩写(128000000)).toBe("¥ 1.28 亿");
    expect(金额缩写(1200000000)).toBe("¥ 12 亿");
    expect(金额缩写(12946000000)).toBe("¥ 129.46 亿");
    expect(金额缩写(-5326000)).toBe("-¥ 532.6 万");
    expect(金额缩写(null)).toBe("¥ 0");
  });
  it("各档上沿按四舍五入后的值定档，不出「10,000 万」「10,000 亿」", () => {
    expect(金额缩写(9999)).toBe("¥ 9,999");
    expect(金额缩写(9_999_499)).toBe("¥ 999.9 万");
    expect(金额缩写(9_999_500)).toBe("¥ 1,000 万");
    expect(金额缩写(99_994_999)).toBe("¥ 9,999 万");
    expect(金额缩写(99_995_000)).toBe("¥ 1 亿");
    expect(金额缩写(99_996_000)).toBe("¥ 1 亿");
    expect(金额缩写(99_999_999)).toBe("¥ 1 亿");
    expect(金额缩写(999_999_499_999)).toBe("¥ 9,999.99 亿");
    expect(金额缩写(999_999_500_000)).toBe("¥ 1 万亿");
    expect(金额缩写(1_234_000_000_000)).toBe("¥ 1.23 万亿");
    expect(金额缩写(-99_996_000)).toBe("-¥ 1 亿");
  });
  it("符号照币种、不换汇；多币种按 合计文字 的顺序连", () => {
    expect(金额缩写(5326000, "USD")).toBe("US$ 532.6 万");
    const 合 = [{ 币种: "CNY", 合计: 128000000 }, { 币种: "USD", 合计: 32100 }];
    expect(合计缩写(合)).toBe("¥ 1.28 亿 · US$ 3.2 万");
    expect(合计文字(合)).toBe("¥ 128,000,000 · US$ 32,100");
    expect(合计缩写([])).toBe("¥ 0");
  });
});
