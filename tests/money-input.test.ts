/**
 * 金额框的 formatter（2026-09-28 审查 S6）。
 *
 * 本机复现过：原来的 parser 把空串读成 0，全选删掉后框里剩「¥ 0」、光标停在最前，
 * 接着敲 18000 存下来的是 180,000。现在敲的时候原样返回人敲的字，失焦后才加千分位。
 */
import { describe, it, expect } from "vitest";
import { 金额格式 } from "@/lib/money-input";

describe("金额框：敲的时候不动人敲的字，失焦后再加千分位", () => {
  it("正在敲：原样返回，不加逗号——光标底下没有东西会挪", () => {
    expect(金额格式(1800, { userTyping: true, input: "1800" })).toBe("1800");
  });
  it("失焦后：加千分位，不带 ¥（¥ 在框外）", () => {
    expect(金额格式(180000, { userTyping: false, input: "" })).toBe("180,000");
    expect(金额格式(18000, { userTyping: false, input: "" })).toBe("18,000");
  });
  it("空着就是空，不是 0", () => {
    expect(金额格式(undefined, { userTyping: false, input: "" })).toBe("");
  });
});

/*
 * 11-20：页面上的金额框原来是 antd InputNumber 默认 parser——「5万」「12.5万」悄悄存成 5、12.5，「3w」停在 3，「-500」失焦压成 0。
 * 现在金额框（components/AmountInput）、AI 卡（AmountTextInput）、导入都走 认金额 / 读金额原文。
 */
import { 认金额, 读金额原文 } from "@/lib/money-input";

describe("认金额：万 / 千 / k / w / 亿，敲到一半的小数", () => {
  it.each([
    ["5万", 50000], ["12.5万", 125000], ["3w", 30000], ["3W", 30000], ["2.5k", 2500], ["8千", 8000], ["1.5亿", 150000000],
    ["5万元", 50000], ["¥1,234.5", 1234.5], ["12.", 12], [".5", 0.5], ["１２．５万", 125000],
  ])("「%s」= %d", (s, n) => {
    expect(认金额(s)).toBe(n);
  });
  it.each(["5万5", "约5万", "面议", "-500", "-5万", "一万", "5万万", ".", "12.5.1"])("「%s」认不出（不截成别的数）", (s) => {
    expect(认金额(s)).toBeNull();
  });
});

describe("读金额原文：框旁说什么", () => {
  it("空、普通数、带单位的换算", () => {
    expect(读金额原文("  ")).toEqual({ 类: "空" });
    expect(读金额原文("18000")).toEqual({ 类: "数", 值: 18000 });
    expect(读金额原文("¥18,000")).toEqual({ 类: "数", 值: 18000 });
    expect(读金额原文("12.5万")).toEqual({ 类: "换算", 值: 125000 });
    expect(读金额原文("3w")).toEqual({ 类: "换算", 值: 30000 });
  });
  it("认不出说原文；超上限不压成上限", () => {
    expect(读金额原文("5万5")).toEqual({ 类: "错", 话: "认不出「5万5」：只填不小于 0 的数字，可带千分位、¥、万 / 千 / k / w" });
    expect(读金额原文("2万亿", 1e12).类).toBe("错");
    expect(读金额原文("20000亿", 1e12)).toEqual({ 类: "错", 话: "「20000亿」超过上限 1,000,000,000,000" });
    expect(读金额原文("9999亿", 1e12)).toEqual({ 类: "换算", 值: 999900000000 });
  });
});
