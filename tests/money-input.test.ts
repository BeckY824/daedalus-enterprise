/**
 * 金额框的 formatter（2026-09-28 审查 S6）。
 *
 * 本机复现过：原来的 parser 把空串读成 0，全选删掉后框里剩「¥ 0」、光标停在最前，
 * 接着敲 18000 存下来的是 180,000。现在敲的时候原样返回人敲的字，失焦后才加千分位。
 */
import { describe, it, expect } from "vitest";
import { 金额格式 } from "@/lib/money-input";

describe("金额框：敲的时候不动人敲的字，失焦后再加千分位", () => {
  it("正在敲：原样返回，不加逗号——光标底下没有东西会挪", () => {
    expect(金额格式(1800, { userTyping: true, input: "1800" })).toBe("1800");
  });
  it("失焦后：加千分位，不带 ¥（¥ 在框外）", () => {
    expect(金额格式(180000, { userTyping: false, input: "" })).toBe("180,000");
    expect(金额格式(18000, { userTyping: false, input: "" })).toBe("18,000");
  });
  it("空着就是空，不是 0", () => {
    expect(金额格式(undefined, { userTyping: false, input: "" })).toBe("");
  });
});

/*
 * 11-20：页面上的金额框原来是 antd InputNumber 默认 parser——「5万」「12.5万」悄悄存成 5、12.5，「3w」停在 3，「-500」失焦压成 0。
 * 现在金额框（components/AmountInput）、AI 卡（AmountTextInput）、导入都走 认金额 / 读金额原文。
 */
import { 认金额, 读金额原文, 金额字币种, 金额字记号 } from "@/lib/money-input";

describe("认金额：万 / 千 / k / w / 亿，敲到一半的小数", () => {
  it.each([
    ["5万", 50000], ["12.5万", 125000], ["3w", 30000], ["3W", 30000], ["2.5k", 2500], ["8千", 8000], ["1.5亿", 150000000],
    ["5万元", 50000], ["¥1,234.5", 1234.5], ["12.", 12], [".5", 0.5], ["１２．５万", 125000],
  ])("「%s」= %d", (s, n) => {
    expect(认金额(s)).toBe(n);
  });
  it.each(["5万5", "约5万", "面议", "-500", "-5万", "一万", "5万万", ".", "12.5.1"])("「%s」认不出（不截成别的数）", (s) => {
    expect(认金额(s)).toBeNull();
  });
});

describe("读金额原文：框旁说什么", () => {
  it("空、普通数、带单位的换算", () => {
    expect(读金额原文("  ")).toEqual({ 类: "空" });
    expect(读金额原文("18000")).toEqual({ 类: "数", 值: 18000, 币: null });
    expect(读金额原文("¥18,000")).toEqual({ 类: "数", 值: 18000, 币: "CNY" });
    expect(读金额原文("12.5万")).toEqual({ 类: "换算", 值: 125000, 币: null });
    expect(读金额原文("3w")).toEqual({ 类: "换算", 值: 30000, 币: null });
  });
  it("认不出说原文；超上限不压成上限", () => {
    expect(读金额原文("5万5")).toEqual({ 类: "错", 话: "认不出「5万5」：只填不小于 0 的数字，可带千分位、¥、万 / 千 / k / w" });
    expect(读金额原文("2万亿", 1e12).类).toBe("错");
    expect(读金额原文("20000亿", 1e12)).toEqual({ 类: "错", 话: "「20000亿」超过上限 1,000,000,000,000" });
    expect(读金额原文("9999亿", 1e12)).toEqual({ 类: "换算", 值: 999900000000, 币: null });
  });
});

/* 审查 11-20：全角字母（「３ｗ」「２．５ｋ」）一并认；币种记号和选的币种对不上不悄悄按选的存 */
describe("全角、币种记号", () => {
  it.each([["３ｗ", 30000], ["２．５ｋ", 2500], ["１２，０００", 12000], ["＄５０００", 5000], ["5000元整", 5000], ["5000整", 5000]])("「%s」= %d", (s, n) => {
    expect(认金额(s)).toBe(n);
  });

  it("字里写的币种：¥ / 元 / RMB / CNY → CNY，$ / US$ / USD → USD，没写 = null；前后对不上（「$5000元」）认不出", () => {
    expect(金额字币种("5000元")).toBe("CNY");
    expect(金额字币种("¥5万")).toBe("CNY");
    expect(金额字币种("RMB5000")).toBe("CNY");
    expect(金额字币种("USD 5000")).toBe("USD");
    expect(金额字币种("5000usd")).toBe("USD");
    expect(金额字币种("US$5,000")).toBe("USD");
    expect(金额字币种("$5000")).toBe("USD");
    expect(金额字币种("5000")).toBeNull();
    expect(金额字币种("5万")).toBeNull();
    expect(认金额("$5000元")).toBeNull();
    expect(认金额("¥5000元")).toBe(5000);
  });

  it.each([
    ["5000元", "USD", "人民币", "美元"],
    ["RMB5000", "USD", "人民币", "美元"],
    ["¥5万", "USD", "人民币", "美元"],
    ["USD 5000", "CNY", "美元", "人民币"],
    ["5000usd", "CNY", "美元", "人民币"],
    ["$5000", "EUR", "美元", "欧元"],
  ])("选了别的币种敲「%s」（选 %s）：算错，说写的是%s、选的是%s", (原文, 选, 写的名, 选的名) => {
    const r = 读金额原文(原文, undefined, 选);
    expect(r.类).toBe("错");
    expect(r.类 === "错" && r.话).toContain(`写的是${写的名}，币种选的是${选的名}`);
  });

  it("对得上、或记号本来就是那种币的（「$」港币也用、「¥」日元也用）、没写记号的：照常认", () => {
    expect(读金额原文("5000元", undefined, "CNY")).toEqual({ 类: "数", 值: 5000, 币: "CNY" });
    expect(读金额原文("USD 5000", undefined, "USD")).toEqual({ 类: "数", 值: 5000, 币: "USD" });
    expect(读金额原文("$5000", undefined, "HKD").类).toBe("数");
    expect(读金额原文("¥5000", undefined, "JPY").类).toBe("数");
    expect(读金额原文("5万", undefined, "USD")).toEqual({ 类: "换算", 值: 50000, 币: null });
    // 「元」只算人民币：选日元写「5000元」算对不上
    expect(读金额原文("5000元", undefined, "JPY").类).toBe("错");
  });
});

/* 审查 11-20 第二轮：导入时金额靠 AI / 模拟清洗补认回来（整串规则认不出），币种照前后的记号定，不落成默认人民币 */
describe("金额字记号：只看前后的币种记号，不要求整串认得出", () => {
  it.each([
    ["5000元", "CNY"], ["5000人民币", "CNY"], ["RMB5000", "CNY"], ["CNY 5000", "CNY"], ["¥5000", "CNY"], ["￥5000", "CNY"], ["5000元整", "CNY"],
    ["$5000", "USD"], ["US$5000", "USD"], ["USD5000", "USD"], ["5000usd", "USD"], ["5000美元", "USD"],
    // 整串认不出、靠补认的：照记号
    ["约5000USD", "USD"], ["约5000USD左右", "USD"], ["大约$5000", "USD"], ["约5万元", "CNY"], ["五千元", "CNY"], ["¥5000元", "CNY"],
  ])("「%s」→ %s", (原, 币) => {
    expect(金额字记号(原)).toMatchObject({ 类: "币", 币 });
  });

  it("没写记号 = 无；前后对不上 = 矛盾；别的币种记号 = 不认得", () => {
    for (const 原 of ["5000", "约5万", "5000整", "5万5"]) expect(金额字记号(原), 原).toEqual({ 类: "无" });
    expect(金额字记号("$5000元")).toEqual({ 类: "矛盾", 记号: ["$", "元"] });
    expect(金额字记号("USD5000元")).toMatchObject({ 类: "矛盾" });
    for (const [原, 记号] of [["HK$5000", "HK$"], ["5000EUR", "EUR"], ["5000港币", "港币"], ["€5000", "€"], ["5000日元", "日元"]] as const) {
      expect(金额字记号(原), 原).toEqual({ 类: "不认得", 记号 });
    }
    // 整串认得出的，和 拆金额 定的一样
    for (const 原 of ["5000元", "¥5万", "RMB5000", "USD 5000", "5000usd", "US$5,000", "$5000", "5000"]) {
      const r = 金额字记号(原);
      expect(r.类 === "币" ? r.币 : null, 原).toBe(金额字币种(原));
    }
  });
});
