/**
 * 项目进程变更里 pool-claim 那一行的标题（lib/project/transfer-log-text.ts 公海领取文字，3703 实操 11-21）：
 * 管理从客户公海分配原来也写「从线索公海领取」。按留痕原因的开头分；各入口写的开头由 ent-reply-overdue-entries.test.ts 钉着
 */
import { describe, it, expect } from "vitest";
import { 公海领取文字, 公海分配痕, 线索公海分配痕, 跟着客户痕, 随客户痕, 离职交接痕 } from "@/lib/project/transfer-log-text";
import * as 老出处 from "@/lib/project/carry-tasks";

const 尾 = "；原负责人没做完的待办带过来 0 条";

describe("pool-claim 标题按实际来源", () => {
  it("管理从客户公海分配（带出线索公海的项目）：写客户公海分配，不写线索公海领取", () => {
    const s = 公海领取文字({ who: "管理员", reason: `${公海分配痕}${尾}`, to: "销售甲" });
    expect(s).toBe("管理员 从客户公海分配，销售甲 成为负责人");
    expect(s).not.toContain("领取");
  });
  it("管理从线索公海分配项目", () => {
    expect(公海领取文字({ who: "管理员", reason: 线索公海分配痕, to: "销售甲" })).toBe("管理员 从线索公海分配，销售甲 成为负责人");
  });
  it("自己去线索公海领（原因只有待办痕或空）：照旧「从线索公海领取」", () => {
    expect(公海领取文字({ who: "销售甲", reason: null, to: "销售甲" })).toBe("销售甲 从线索公海领取，成为负责人");
    expect(公海领取文字({ who: "销售甲", reason: "原负责人没做完的待办没带", to: "销售甲" })).toBe("销售甲 从线索公海领取，成为负责人");
  });
  it("跟着客户 / 随客户 / 离职交接一起出线索公海的", () => {
    for (const 头 of [跟着客户痕, 随客户痕, 离职交接痕]) {
      expect(公海领取文字({ who: "管理员", reason: `${头}${尾}`, to: "销售甲" }), 头).toBe("项目跟着客户出线索公海，销售甲 成为负责人");
    }
  });
  it("11-20 以前没写开头、别人分的老留痕：不说是哪个公海，也不说是领取", () => {
    expect(公海领取文字({ who: "管理员", reason: null, to: "销售甲" })).toBe("管理员 从公海分配，销售甲 成为负责人");
  });
  it("carry-tasks 照旧导出这几个开头（老 import 不改），值不变", () => {
    expect([老出处.随客户痕, 老出处.跟着客户痕, 老出处.离职交接痕, 老出处.公海分配痕, 老出处.线索公海分配痕, 老出处.手动转让痕])
      .toEqual(["随客户转走", "跟着客户转过来", "离职交接", "从客户公海分配", "从线索公海分配", "手动转让"]);
  });
});
