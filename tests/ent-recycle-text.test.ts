/**
 * 企业版回公海文案 + 记沟通时的回收日预演（lib/enterprise/recycle-text.ts，2026-10-30 交互调整 P0-1 / P0-2）。
 *   - 文案写具体日子和天数；3 天内标「近」、当天 / 已过标红
 *   - 预演和 timeout.ts 超时回收日 同一个算法：拿同几组数对一遍，算法以后改了这里会红
 */
import { describe, it, expect } from "vitest";
import { 回公海文案, 预演回收日 } from "@/lib/enterprise/recycle-text";
import { 超时回收日 } from "@/lib/project/timeout";
import { 默认组织规则 } from "@/lib/project/org-rules";

const 今 = "2026-10-30T10:00:00+08:00";

describe("回公海文案", () => {
  it("还早：写日子和还剩几天，不标色", () => {
    expect(回公海文案("2026-11-06", 今)).toEqual({ 文字: "11-06 回公海 · 还剩 7 天", 短文字: "11-06 回公海", 剩天: 7, 级别: "常" });
  });
  it("3 天内标「近」；明天的短文字写「明天回公海（日子）」", () => {
    expect(回公海文案("2026-11-02", 今).级别).toBe("近");
    expect(回公海文案("2026-11-04", 今).级别).toBe("常");
    expect(回公海文案("2026-10-31", 今)).toMatchObject({ 文字: "10-31 回公海 · 还剩 1 天", 短文字: "明天回公海（10-31）", 级别: "近" });
  });
  it("当天、已过", () => {
    expect(回公海文案("2026-10-30", 今)).toMatchObject({ 文字: "今天回公海（10-30）", 级别: "当天", 剩天: 0 });
    expect(回公海文案("2026-10-28", 今)).toMatchObject({ 文字: "已过回收日（10-28）", 级别: "已过" });
  });
  it("跨年写全年份", () => {
    expect(回公海文案("2027-01-03", "2026-12-30T10:00:00+08:00").文字).toBe("2027-01-03 回公海 · 还剩 4 天");
  });
});

describe("预演回收日", () => {
  const 底子 = { 起点日: "2026-10-25", 天数: 7 };

  it("没选下一步时间、没有底子、天数不对：不预演", () => {
    expect(预演回收日(底子, "2026-10-30", null)).toBeNull();
    expect(预演回收日(null, "2026-10-30", "2026-11-01")).toBeNull();
    expect(预演回收日({ 起点日: "2026-10-25", 天数: 0 }, "2026-10-30", "2026-11-01")).toBeNull();
    expect(预演回收日(底子, "2026-10-30", "不是日子")).toBeNull();
  });

  it("这条沟通把起点推到今天：下一步那天过完就收，但不晚于起点 + 天数", () => {
    expect(预演回收日(底子, "2026-10-30", "2026-10-31")).toBe("2026-11-01");
    expect(预演回收日(底子, "2026-10-30", "2026-11-03")).toBe("2026-11-04");
    expect(预演回收日(底子, "2026-10-30", "2026-11-20")).toBe("2026-11-06");
  });

  it("补记一条比起点早的沟通：起点不往回退", () => {
    expect(预演回收日(底子, "2026-10-20", "2026-11-20")).toBe("2026-11-01");
  });

  it("和 timeout.ts 超时回收日 算的一样", () => {
    const 规则 = { ...默认组织规则, 超时回收: { 开: true, 节点天数: { 潜客培育: 7 } } };
    for (const [沟通日, 下一步日] of [["2026-10-30", "2026-10-31"], ["2026-10-30", "2026-11-30"], ["2026-10-20", "2026-10-26"], ["2026-10-28", "2026-10-28"]]) {
      const 起点 = 沟通日 > 底子.起点日 ? 沟通日 : 底子.起点日;
      expect(预演回收日(底子, 沟通日, 下一步日)).toBe(超时回收日(规则, { phase: "线索", node: "潜客培育", nextStepAt: 下一步日 }, `${起点}T09:00:00+08:00`));
    }
  });
});
