/**
 * 设置开关 N9（11-23）：改组织规则的操作日志摘要写「哪项从什么变成什么」。
 * 原来改「前两个进程要沟通」「需求补全期」时摘要写成「往前推权限 X，改了 N 个阶段的结束状态叫法」，看不出改的是哪项；
 * 开关总览每张卡的「上次」也靠这一份比相邻两行 detail（N5）
 */
import { describe, it, expect } from "vitest";
import { 默认组织规则, type 组织规则 } from "@/lib/project/org-rules";
import { 组织规则改动, 组织规则改动摘要 } from "@/lib/project/org-rules-diff";

const 改 = (f: (r: 组织规则) => void): 组织规则 => {
  const r = structuredClone(默认组织规则);
  f(r);
  return r;
};

describe("组织规则改动摘要", () => {
  it("阶段开关：写哪项从关变开，不再写成往前推权限和叫法", () => {
    const 新 = 改((r) => { r.阶段.前两节点要沟通 = true; });
    expect(组织规则改动摘要(默认组织规则, 新)).toBe("组织规则：前两个进程要沟通：关 → 开");
    expect(组织规则改动摘要(新, 改((r) => { r.阶段.前两节点要沟通 = true; r.阶段.需求补全期 = true; }))).toBe("组织规则：需求状态补全期：关 → 开");
    expect(组织规则改动摘要(默认组织规则, 改((r) => { r.阶段.推进权限 = "仅上级推"; }))).toBe("组织规则：谁能往前推进程：负责人可推 → 仅上级推");
  });

  it("节点推进范围、持有上限、超时回收各写各的；几项一起改用「；」隔开", () => {
    const 新 = 改((r) => { r.节点推进.开 = true; r.节点推进.范围 = "新建"; r.公海.持有上限开 = true; r.公海.默认上限 = 999; });
    expect(组织规则改动摘要(默认组织规则, 新)).toBe(
      "组织规则：项目持有上限：关 → 开；项目持有上限默认：30 个 → 不限；节点推进：关 → 开；节点推进管哪些项目：全部项目 → 开启之后新建的",
    );
  });

  it("一项都没变也留一句", () => {
    expect(组织规则改动摘要(默认组织规则, 默认组织规则)).toBe("组织规则：没有改动");
  });

  it("每处改动带上属于哪个开关和卡上的动词（开关总览「上次」那行用）", () => {
    const 新 = 改((r) => { r.超时回收.开 = true; r.节点推进.必填 = { 潜客培育: ["来源"] }; r.三态.开 = true; r.阶段.培育计划上限 = 200; });
    expect(组织规则改动(默认组织规则, 新).map((x) => [x.开关 ?? null, x.动作])).toEqual([
      ["node_timeout", "打开"],
      ["node_advance", "改必填"],
      [null, "改字数上限"],
      ["tri_state", "打开"],
    ]);
  });
});
