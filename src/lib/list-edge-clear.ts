/**
 * 列表横滚停在最左时，表头字别被右边钉住的操作列（和它左边那道 --edge-fade 渐隐）压成半截（设计语言 C-A2 · C-新6）。
 *
 * 做法：给指定的一列（DataList 的 补宽列，渠道页是「渠道属性」）多给一点宽，把它后面所有列往右推，
 * 推到「看得见的最后一个表头，字的右沿在渐隐左边」「下一个表头整个藏进钉住列底下」为止。只推不挤，推的量取最小的。
 *
 * 字：补宽列后面、不钉住的各列表头字的左右沿（表格坐标、已减掉当前补宽，即「不补时」的位置）
 * 界：钉住的操作列左沿（表格坐标，横滚 0 时）
 * 渐隐：渐隐宽（24）
 * 上限：最多补这么多，超了就不补（返回 0），免得某一列特别宽时把名字列后面推出一大片空
 */
export function 躲开钉住列补宽(字: { 左: number; 右: number }[], 界: number, 渐隐: number, 上限: number): number {
  const 行 = (d: number) => 字.every((t) => t.右 + d <= 界 - 渐隐 || t.左 + d >= 界);
  const 候选 = [0, ...字.map((t) => Math.ceil(界 - t.左))].filter((d) => d >= 0 && d <= 上限).sort((a, b) => a - b);
  for (const d of 候选) if (行(d)) return d;
  return 0;
}
