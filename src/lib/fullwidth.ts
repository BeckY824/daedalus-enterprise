/**
 * 全角转半角，全仓库只这一处（代码质量体检 G1）。原来内联抄了 11 处、范围有三种，各处行为不一样，所以是三个函数、不是一个：
 *
 *   - 全角数字转半角：只转 ０-９。号码那几处用（规整手机号、占位号、搜索、打码、建档验号）
 *   - 全角数字和点转半角：０-９ 和 ．。金额用（「１２．５万」）
 *   - 全角转半角：！-～ 整段（U+FF01–U+FF5E，数字、字母、标点）。比名字、认表头、认档位用
 *
 * 三个都**不碰全角空格**（U+3000）和 ！-～ 以外的全角字（「。」「、」「￥」）：要去空格、要转别的字，调用方自己接着做。
 * 纯函数，浏览器和服务端都能用；不引任何东西。
 */

const 挪 = (c: string) => String.fromCharCode(c.charCodeAt(0) - 0xfee0);

/** 只转全角数字 ０-９。全角加号、横杠、点、字母都原样留着 */
export function 全角数字转半角(s: string): string {
  return s.replace(/[０-９]/g, 挪);
}

/** 全角数字 ０-９ 和全角点 ．（金额里的小数点）。别的原样留着 */
export function 全角数字和点转半角(s: string): string {
  return s.replace(/[０-９．]/g, 挪);
}

/** ！-～ 整段（U+FF01–U+FF5E）：全角数字、字母、标点都转。全角空格不转 */
export function 全角转半角(s: string): string {
  return s.replace(/[！-～]/g, 挪);
}
