/**
 * 换人留痕（ProjectNodeLog kind transfer / pool-claim）原因的几种开头，和项目详情「项目进程变更」里 pool-claim 那一行的标题。
 * 纯数据和纯函数：项目详情（客户端组件）也 import，所以不放 carry-tasks.ts（那边连着库，从那边照旧 re-export，老的 import 不用改）。
 *
 * 换人留痕原因的几种开头（超时未跟进自动转 reply-overdue.ts 算起算：公海分配痕 / 线索公海分配痕 / 手动转让痕 起算，别的原因都算「跟着带过去的」不起算；改字要一起改那边的用例）。
 * 跟着客户痕：客户转让、查重领取、管理分客户时跟着客户一起转过去的项目（随客户痕 只留给市场转给销售，「我分出去的」认它）；
 * 离职交接痕：离职交接（交客户、交项目、全部交给）转过去的项目；
 * 公海分配痕：管理从客户公海分客户时一起带出线索公海的项目（这一条算分给他）；线索公海分配痕、手动转让痕 见下
 */

/**
 * 市场首次分给销售（X-18）时跟着客户走的项目，转让痕的 reason 记这一句。
 * 这些项目不写分配记录（不占额度），「我分出去的」（lead-assign.ts）靠这一句认；项目详情的换人记录里也原样淡色显示
 */
export const 随客户痕 = "随客户转走";
export const 跟着客户痕 = "跟着客户转过来";
export const 离职交接痕 = "离职交接";
export const 公海分配痕 = "从客户公海分配";
/** 管理从线索公海分配项目（分配公海项目，pool-assign-projects.ts）：被分的那条项目那行 pool-claim 的开头，算分给他（含客户还在市场手里、跟着市场转的） */
export const 线索公海分配痕 = "从线索公海分配";
/** 手动转让（改项目）没碰待办时（待办痕 为空）记这一句，算分给他 */
export const 手动转让痕 = "手动转让";

/**
 * 项目进程变更里 pool-claim（出线索公海、换上负责人）那一行的标题（3703 实操 11-21：管理从客户公海分配也写成「从线索公海领取」，容易误读）。
 * 只看留痕原因的开头和操作人，不改库里的老留痕：
 *   - 「从客户公海分配」：管理从客户公海分客户，名下线索公海里的项目一起带出来 → 「X 从客户公海分配，Y 成为负责人」
 *   - 「从线索公海分配」：管理从线索公海分项目 → 「X 从线索公海分配，Y 成为负责人」
 *   - 跟着客户 / 随客户 / 离职交接：项目跟着客户（交接）一起出线索公海 → 「项目跟着客户出线索公海，Y 成为负责人」
 *   - 操作人不是接手人、又没这几个开头（11-20 以前的老留痕：那时管理分客户公海、分线索公海都没写开头，分不出是哪个公海）→ 「X 从公海分配，Y 成为负责人」
 *   - 其余（操作人就是接手人）：自己去领的 → 「Y 从线索公海领取，成为负责人」。
 *     自己领客户公海里的客户、顺带出来的项目也落在这里：那一行和自己领线索公海项目写的一模一样（原因只有待办痕或空），单看留痕分不出
 */
export function 公海领取文字(l: { who: string; reason: string | null; to: string }): string {
  const 因 = l.reason ?? "";
  if (因.startsWith(公海分配痕)) return `${l.who} 从客户公海分配，${l.to} 成为负责人`;
  if (因.startsWith(线索公海分配痕)) return `${l.who} 从线索公海分配，${l.to} 成为负责人`;
  if ([跟着客户痕, 随客户痕, 离职交接痕].some((头) => 因.startsWith(头))) return `项目跟着客户出线索公海，${l.to} 成为负责人`;
  if (l.who !== l.to) return `${l.who} 从公海分配，${l.to} 成为负责人`;
  return `${l.to} 从线索公海领取，成为负责人`;
}
