/**
 * 线索验证面板顶上的「判定依据」（员工反馈 #7：判定依据不明确）。只把系统真在用的判法写成白话，不另立规矩：
 *   - 判有效：要先有有效沟通 = 线索验证节点配的必填项（不含有效沟通、线索验证结果）都齐，没配看需求状态
 *     （required.ts 有效沟通要的 / 有效沟通还差，stage-gates.ts 企业版推进关；M-线索-01、M-必填-02、M-必填-03），所有角色都过这道门；
 *     判有效推到「线索推进」（lead-verify.ts 销售初判）
 *   - 判无效：要写无效原因；创建人是销售 → 初判即终判；不然交市场复核（规则关了 / 没有市场管理 → 直接交总管理终判），
 *     复核或终判判无效才算无效线索，项目记线索流失（lead-verify.ts 判死；M-线索-02）
 *   - 还需培育：回潜客培育 + 一条跟进计划
 *   - 老客户再下单：客户详情「更多操作 ▾」→ 新建项目，新建只能落在线索验证及之前（stage-gates.ts 建档不能过线索验证），同样过这一步
 * 需求状态写明在「项目画像」卡里选（F-017：销售在「项目资料」卡里找不到）。
 * 界面上不露内部岗位名：复核的人说「管理员」，销售说「负责人」（和面板其他字一致）。只引 required.ts（界面能引，不碰 prisma）
 */
import { 有效沟通要的, 必填叫法, type 必填项 } from "./required";

export type 判定依据 = { 有效: string; 无效: string; 培育: string; 复购: string };

export function 线索验证依据(o: {
  /** 组织规则里「线索验证」节点配的必填（节点必填(规则, "线索验证")；没开节点推进 = 空） */
  线索验证必填: readonly 必填项[];
  初判即终判: boolean;
  无效交给?: "市场复核" | "总管理终判";
}): 判定依据 {
  const 要的 = 有效沟通要的(o.线索验证必填);
  const 只看需求 = 要的.length === 1 && 要的[0] === "需求" && !o.线索验证必填.includes("需求");
  const 有效 = 只看需求
    ? "判有效：项目的「需求状态」要先选上（在项目页「项目画像」卡里选，选了任一项都算，显示「—」不算）；没选「有效」按钮是灰的。所有角色都一样。判有效后推到「线索推进」。"
    : `判有效：项目里这几项要先填齐——${要的.map(必填叫法).join("、")}（「线索验证」配的必填项）${要的.includes("需求") ? "，需求状态在项目页「项目画像」卡里选" : ""}；没齐「有效」按钮是灰的。所有角色都一样。判有效后推到「线索推进」。`;
  const 无效 = o.初判即终判
    ? "判无效：要写无效原因。项目是销售建的，负责人判无效就是最终结果，记为线索流失，不再交管理员复核。"
    : o.无效交给 === "总管理终判"
      ? "判无效：要写无效原因，交管理员最终确认。确认无效才算无效线索（记为线索流失）；确认有效回到负责人认领。"
      : "判无效：要写无效原因，交管理员复核。复核也判无效才算无效线索（记为线索流失）；复核判有效回到负责人确认，负责人有异议再交管理员最终确认。";
  return {
    有效,
    无效,
    培育: "还需培育：回到「线索·潜客培育」，按选的日子排一条跟进计划。",
    复购: "老客户再下单：在客户详情「更多操作 ▾」→「新建项目」，新项目从线索阶段起，同样要过这一步。",
  };
}
