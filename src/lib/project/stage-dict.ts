/** 后台改的出口叫法：每个阶段 [走成, 没走成]，null / 空 = 用字典里的 */
export type 出口叫法改动 = Partial<Record<阶段, readonly [string | null, string | null]>>;

/**
 * 用哪套：服务端传 企业版()，界面传服务端给的 企业版。
 * 叫法 = 后台改的出口叫法（组织规则 阶段.出口叫法，只企业版认）：只换说法，结局、节点、规矩都不变
 */
export function 字典of(企业版: boolean, 叫法?: 出口叫法改动 | null): 阶段字典 {
  if (!企业版) return 团队版字典;
  if (!叫法 || !Object.values(叫法).some((v) => v && (v[0] || v[1]))) return 企业版字典;
  const 出口们 = { ...企业版字典.出口们 };
  for (const s of 阶段们) {
    const v = 叫法[s];
    if (!v) continue;
    const [成, 没成] = 企业版字典.出口们[s];
    出口们[s] = [{ ...成, 叫法: v[0] || 成.叫法 }, { ...没成, 叫法: v[1] || 没成.叫法 }];
  }
  return { ...企业版字典, 出口们 };
}

/** 一个阶段在对方表里的全部值：节点 + 两个出口 */
export function 阶段值们(字典: 阶段字典, s: 阶段): string[] {
  return [...字典.节点们[s], ...字典.出口们[s].map((o) => o.叫法)];
}

/** 结局在界面上的叫法（后台改了出口叫法就用改的）；库里存的旧名先对到新名；认不出的原样 */
export function 结局叫法(r: string, 字典: 阶段字典 = 团队版字典): string {
  const 新 = 本套名(r, 字典);
  for (const s of 阶段们) for (const o of 字典.出口们[s]) if (o.结局 === 新) return o.叫法;
  return 新;
}

/** 按团队版写的节点名 / 结局（或库里存着的旧名）对到这套（见 改名）；不用改名的原样。节点、结局都走这个 */
export function 本套名(v: string, 字典: 阶段字典): string {
  return 字典.改名[v] ?? v;
}

/**
 * 按节点名存的配置（节点天数、必填）把 key 对到这套的名字：存着的旧 key（企业版 10-31 改名前存的）当新名用；
 * 新旧 key 都在时以新 key 为准
 */
export function 按本套名<V>(们: Record<string, V>, 字典: 阶段字典): Record<string, V> {
  const 出: Record<string, V> = {};
  for (const [k, v] of Object.entries(们)) {
    const 新 = 本套名(k, 字典);
    if (新 !== k && 新 in 们) continue;
    出[新] = v;
  }
  return 出;
}

/** 本套名 的老名字（节点用），意思一样 */
export const 本套节点名 = 本套名;

/** 同一个节点 / 结局在两套里的全部名字（新名 + 旧名），不分版本：库里按 node / result 查（in）、按名取配置都用它 */
export function 同名们(v: string): string[] {
  const 新 = 企业版旧名换新名[v] ?? v;
  const 旧们 = Object.keys(企业版旧名换新名).filter((k) => 企业版旧名换新名[k] === 新);
  return [新, ...旧们];
}

/** 订单走成的结局（团队版 成功交付 / 企业版 交付结清，库里旧名也认）：别再写 === "成功交付" */
export function 是交付(r: string | null | undefined): boolean {
  return r === "成功交付" || r === "交付结清";
}

/** 这套的结局们（按出口们，顺序：线索流失、丢单、交付、异常状态） */
export function 结局们of(字典: 阶段字典): 结局[] {
  const 们: 结局[] = [];
  for (const s of 阶段们) for (const o of 字典.出口们[s]) if (o.结局 && !们.includes(o.结局)) 们.push(o.结局);
  return 们;
}

/**
 * 阶段、进程分开摆（P11，10-29）：阶段 = 线索 / 商机 / 订单，进程 = 节点（潜客培育、验收交付…），界面上不再拼成「线索·潜客培育」一串。
 * 有结局的按结局认阶段（出口们里它挂在哪个阶段）：成功交付、异常状态归订单，线索流失归线索，丢单归商机——不看库里 phase。
 * 结局 = 按字典的叫法（后台改了出口叫法就用改的），没结局 = null
 */
export function 阶段与进程(
  p: { phase: string; node: string; result?: string | null },
  字典: 阶段字典 = 团队版字典,
): { 阶段: string; 进程: string; 结局: string | null } {
  const r = p.result ? 本套名(p.result, 字典) : null;
  const 归 = r ? 阶段们.find((s) => 字典.出口们[s].some((o) => o.结局 === r)) : undefined;
  return { 阶段: 归 ?? p.phase, 进程: 本套节点名(p.node, 字典), 结局: p.result ? 结局叫法(p.result, 字典) : null };
}
