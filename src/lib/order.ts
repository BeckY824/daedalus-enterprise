/**
 * 按贸易条款默认要收的单据（2.8 那张表）。「选」「客户要才要」的不默认列，要的人自己加一行。
 * 没写条款时按 FOB：小贸易公司最常见。
 */
export function 默认单据(incoterm?: string | null): string[] {
  const 条 = (incoterm ?? "FOB").toUpperCase();
  const 出口自己办 = 条 !== "EXW"; // EXW 客户自己提货：不订舱、不报关、不出提单
  const 我方投保 = 条 === "CIF" || 条 === "DAP" || 条 === "DDP";
  return [
    "报价单 Quotation",
    "形式发票 PI（客户签回）",
    "定金水单",
    "采购合同",
    ...(出口自己办 ? ["订舱单 S/O"] : []),
    "装箱单 PL",
    "商业发票 CI",
    ...(出口自己办 ? ["报关单", "提单 B/L"] : []),
    ...(我方投保 ? ["保险单"] : []),
    "尾款水单",
  ];
}

/**
 * 订单号默认「年月日-序号」：20261003-1。和 DDW 那种「国家缩写 + 年月日 + 序号」比少了国家——
 * 客户国家我们不一定有；人可以自己改成 PI 号。`今天已有` 是今天已经用掉的号（同一天第二单就是 -2）。
 */
export function 默认订单号(今天已有: string[], 现在: Date = new Date(), 前缀 = ""): string {
  const 日 = `${前缀}${businessDayjs(现在).format("YYYYMMDD")}`;
  let n = 1;
  while (今天已有.includes(`${日}-${n}`)) n++;
  return `${日}-${n}`;
}

/**
 * 团队模式下订单号的前缀：业务员名字的第一个字（「甲-20261003-1」）。
 * 几台电脑各自从 -1 开始编号，同一天会撞成同号的两张单（团队同步探针验出来的）；带上人就分开了。
 */
export function 团队订单前缀(名字: string | null | undefined): string {
  const 字 = [...String(名字 ?? "").trim()][0];
  return 字 ? `${字}-` : "";
}
