/**
 * 从客户名称里拆出联系人姓名（E-260，11-24）：客户没有电话这一说法，号码一律记在联系人上。
 * 号码要落到主联系人、客户又没有联系人时（导入、定时同步、老线索转项目、没带联系人的新建），新建的那位联系人按这里起名：
 * 客户名称里能认出人名（「张三｜美国」「李总 13800001111」「John Smith / USA」）就用它，认不出（单位名、空的）留空串（界面显示「—」）。
 * 认人名和全称软提示同一把尺（fullname-hint.ts 段像人名），只认得出才填、不猜。
 * 代码入口和数据脚本（给没联系人的客户建主联系人）共用这一份。纯函数，不碰库。
 */
import { 段像人名 } from "./fullname-hint";

/** 联系人姓名最长存这么多（拆出来的本来就短，防一手） */
const 姓名上限 = 50;

/** 段与段之间的分隔：竖线、斜杠、顿号、逗号、分号、冒号、各种括号、横杠 */
const 分隔 = /[｜|/／\\、,，;；:：()（）[\]【】<>《》「」『』—–\-~～#＃*]+/;

/** 号码样的一串（数字、+、空格、横杠混写，至少 5 位数字）先挖掉，别让「张三13800001111」认不出 */
const 号码串 = /\+?\d[\d\s\-－]{3,}\d/g;

/** 客户名称 → 联系人姓名；认不出返回空串 */
export function 客户名拆人名(客户名: string | null | undefined): string {
  const 原 = String(客户名 ?? "").replace(/[​-‍﻿]/g, "").replace(/　/g, " ");
  if (!原.trim()) return "";
  const 去号 = 原.replace(号码串, " ").replace(/\d+/g, " ");
  for (const 段 of 去号.split(分隔)) {
    const t = 段.replace(/\s+/g, " ").trim();
    if (!t) continue;
    if (段像人名(t)) return t.slice(0, 姓名上限);
    // 一段里还夹着空格（「深圳 张三」「张三 外贸」）：拆开再认一遍；英文名（John Smith）整段已经认过
    for (const 词 of t.split(" ")) if (词 && 段像人名(词)) return 词.slice(0, 姓名上限);
  }
  return "";
}
