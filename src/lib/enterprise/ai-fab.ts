import { 企业版亮项 } from "./nav";

/**
 * 企业版项目模式右下角那枚 AI 浮标（定稿 #13：首页以外的根目录，右下角圆形 Agent 浮标，类 Siri）。
 * 点了打开的是壳里现有的 AI 面板（AiDock，#14），对话范围照旧按页（ai-context-page.ts），这里只管出不出现。
 *
 *   - 只在企业版 + 项目模式、登录了 AI 时出现；别的版本照旧只有左栏「问一句」
 *   - 只在根目录那几条线上出现：看板、渠道、公海、客户、项目，连同挂在它们下面的页（档案、新线索、跟进、联系人）。
 *     认法和左栏亮项是同一个函数（企业版亮项），左栏亮着哪一项，浮标就跟着那一项走；设置、反馈这类认不出的页不出现
 *   - 首页不出现：首页本身就是对话（AiDock 在首页也不画）
 *   - 面板开着不出现：宽屏常驻时面板已经在右边了，浮标再挂一枚是两个入口打架；
 *     手机上面板盖满整屏，浮标藏起来也就不会挡住输入框
 * 路径给地址栏的 pathname：设置浮层开着时地址是 /settings，认不出亮项，浮标让开、不压在设置上面。
 */
export function 浮标显示(路径: string, pool: string | null, o: { 企业版项目: boolean; 有AI: boolean; 面板开着: boolean }): boolean {
  if (!o.企业版项目 || !o.有AI || o.面板开着) return false;
  const 项 = 企业版亮项(路径, pool);
  return 项 !== null && 项 !== "/dashboard";
}
