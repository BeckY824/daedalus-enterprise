/**
 * 企业版自动分配「都已满额」「待分配」提醒（A8，2026-10-26；A10 11-01）：铃铛 + 飞书，一次点击（单条或批量）发一条，列出没分出去的线索。
 *
 * - 满额：自动分配因为能接的人都分满了、一条没分出去，告诉市场管理、总管理员去找销售的上级调配额。
 * - 待分配：新建线索选了自动分配、但这条业务线没人可分或业务线是「暂不分配」、定时分配到点分不出去、取消定时……线索留在新线索等人手动分，
 *   告诉市场管理、销售管理、总管理员；「线索分配」开关关着只告诉总管理员（X-79）。
 *
 * 11-21 起不再往每人的 Setting（entLeadFullNotice:<userId>）存快照、首页和新线索页顶上不再一条一张黄卡：
 * 首页改成一行「待分配新线索 N 条」，条数从库里现数，分走自动少（await-assign-core.ts / await-assign-scope.ts）。
 * 库里已有的老快照不清、不再读
 */
import { 管理员类别们of, type 组织 } from "./org-core";
import { 企业版 } from "./switch";
import { notify } from "./notify";
import { 规则开着 } from "./rules";
import { 挑不到原因 } from "./await-assign-core";

export type 提醒原因 = "满额" | "待分配";

/**
 * 收提醒的人：组织里的市场管理、总管理员（只认业务角色，11-01；账号管理员没设业务角色的收不到）。
 * 只给总管理员：规则「线索分配和配额」关着时的待分配——市场管理、销售管理分不了，已进待分配的由系统管理员处理（X-79 → P-转-03）
 */
export function 满额提醒收件人(org: 组织, 原因: 提醒原因 = "满额", 只给总管理员 = false): string[] {
  return [...org.成员.keys()].filter((id) => {
    const 类们 = 管理员类别们of(org, id);
    if (只给总管理员) return 类们.has("总管理员");
    // 待分配的线索销售管理也能手动分（11-01 A7），一起提醒
    return 类们.has("市场管理") || 类们.has("总管理员") || (原因 === "待分配" && 类们.has("销售管理"));
  });
}

/** 发一条（铃铛 + 飞书）：线索名是这一次点击里没分出去的那几条；空的不发，不是企业版不发 */
export async function 发满额提醒(org: 组织, 线索: string[], 谁点的: string, 今 = new Date(), 另: { 原因?: 提醒原因; 为什么?: string } = {}): Promise<void> {
  if (!企业版()) return;
  const 收件人 = 满额提醒收件人(org, 另.原因, 另.原因 === "待分配" && !(await 规则开着("线索分配")));
  if (!线索.length || !收件人.length) return;
  const id = `${今.getTime().toString(36)}${Math.random().toString(36).slice(2, 8)}`;
  // 为什么只要原因本身：挑不到人回的那句带着「这条新线索留在原处，可以手动指派」，和后面「线索留在新线索」矛盾（11-21）
  const 为什么 = 另.为什么 ? 挑不到原因(另.为什么) : "";
  const 名单 = `${线索.slice(0, 10).join("、")}${线索.length > 10 ? ` 等 ${线索.length} 条` : ""}`;
  // 待分配不是满额：这条业务线没人可分或选了暂不分配
  await notify(收件人, 另.原因 === "待分配" ? {
    kind: "待分配",
    title: `待分配：${线索.length} 条新线索没自动分出去`,
    body: `${名单}（${谁点的} 建的）。${为什么 ? `${为什么}。` : ""}线索留在新线索、没有负责人：去新线索手动分。`,
    link: "/leads",
    key: `full:${id}`,
  } : {
    kind: "满额",
    title: `自动分配没分出去：${线索.length} 条线索都已满额`,
    body: `${谁点的} 点的自动分配，能接的人都分满了：${名单}。找销售的上级调配额，或者手动分。`,
    link: "/leads",
    key: `full:${id}`,
  });
}

/** 新建线索选了自动分配、没分出去（这条业务线没人可分），留在新线索待分配：告诉市场管理、销售管理、总管理员（A7 / A10）；「线索分配」开关关着只告诉总管理员（X-79） */
export async function 发待分配提醒(org: 组织, 线索: string[], 谁建的: string, 为什么: string, 今 = new Date()): Promise<void> {
  await 发满额提醒(org, 线索, 谁建的, 今, { 原因: "待分配", 为什么 });
}
