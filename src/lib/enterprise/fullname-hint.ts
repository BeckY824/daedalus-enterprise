/** 一段（全称按「｜」拆开的一段）像不像人名 */
function 段像人名(s: string): boolean {
  const t = s.trim();
  if (!t || 单位字样.test(t)) return false;
  // 「张总」「李先生」「王女士」「陈经理」这类称呼
  if (/^[一-龥]{1,3}(总|先生|女士|小姐|经理|老板|老师|姐|哥)$/.test(t)) return true;
  // 两到四个汉字、打头是常见姓
  if (/^[一-龥]{2,4}$/.test(t)) {
    if (复姓.some((x) => t.startsWith(x)) && t.length >= 3) return true;
    return 单姓.has(t[0]) && t.length <= 3;
  }
  // Mr / Mrs / Ms / Dr 开头，或两三个首字母大写的英文词（John Smith）
  if (/^(mr|mrs|ms|miss|dr)\.?\s+\S/i.test(t)) return true;
  return /^[A-Z][a-z]+(\s+[A-Z][a-z]+){1,2}$/.test(t);
}

/** 全称像人名（按「｜」「|」拆开，任一段像就算；「姓名｜国家」这种老补名也认得出） */
export function 全称像人名(全称: string | null | undefined): boolean {
  return String(全称 ?? "")
    .split(/[｜|]/)
    .some(段像人名);
}

/** 全称那一格下面摆的灰字：没填 → 怎么显示；像人名 → 提醒；其余没有 */
export function 全称提示(全称: string | null | undefined): string | null {
  const t = String(全称 ?? "").trim();
  if (!t) return 没填全称提示;
  return 全称像人名(t) ? 像人名提示 : null;
}

