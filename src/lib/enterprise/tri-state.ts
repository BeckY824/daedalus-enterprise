/* ---------- 日子 ---------- */

const 转日 = (d: string) => {
  const [y, m, dd] = d.split("-").map(Number);
  return Date.UTC(y, m - 1, dd);
};
const 出日 = (t: number) => new Date(t).toISOString().slice(0, 10);
const 一天 = 86_400_000;
export const 加天 = (d: string, n: number) => 出日(转日(d) + n * 一天);
/** b − a 差几天 */
export const 差天 = (a: string, b: string) => Math.round((转日(b) - 转日(a)) / 一天);
/** 往前 / 往后挪几个月，月底按那个月最后一天 */
export function 加月(d: string, n: number): string {
  const [y, m, dd] = d.split("-").map(Number);
  const 月 = m - 1 + n;
  const 年 = y + Math.floor(月 / 12), 月份 = ((月 % 12) + 12) % 12;
  const 月末 = new Date(Date.UTC(年, 月份 + 1, 0)).getUTCDate();
  return 出日(Date.UTC(年, 月份, Math.min(dd, 月末)));
}
const 是周一 = (d: string) => new Date(转日(d)).getUTCDay() === 1;
const 较晚 = (...ds: (string | null | undefined)[]) => ds.filter((x): x is string => !!x).reduce<string | null>((a, b) => (a === null || b > a ? b : a), null);

/* ---------- 换负责人 ---------- */

const 计次方式: readonly 换负责人方式[] = ["转让", "离职交接"];

/**
 * 这次换负责人归不归零（M-公海-20）：只看「转让 / 离职交接」，同一客户窗口月数之内（不含这次）已经满次数就不归零；
 * 捞取、公海指派、市场首次分配总归零、也不计次。调用方在转让当时调一次、把结果存进记录的「归零」
 */
export function 换负责人归零(以前: readonly 换负责人记录[], 这次: Pick<换负责人记录, "日" | "方式">, 规则: Pick<三态规则, "转让归零">): boolean {
  if (!计次方式.includes(这次.方式)) return true;
  const 窗口起 = 加月(这次.日, -规则.转让归零.窗口月数);
  const 已有 = 以前.filter((x) => 计次方式.includes(x.方式) && x.日 > 窗口起 && x.日 <= 这次.日).length;
  return 已有 < 规则.转让归零.次数;
}

/** 最近一次算数（归零）的换负责人日；没存「归零」的按记录先后用现在的规则补算 */
function 算数换负责人日(记录们: readonly 换负责人记录[], 规则: 三态规则): string | null {
  const 排好 = [...记录们].sort((a, b) => (a.日 < b.日 ? -1 : a.日 > b.日 ? 1 : 0));
  let 最近: string | null = null;
  排好.forEach((x, i) => {
    const 归 = x.归零 ?? 换负责人归零(排好.slice(0, i), x, 规则);
    if (归) 最近 = 较晚(最近, x.日);
  });
  return 最近;
}

/* ---------- 成交、套 ---------- */

/** 「成交过」此刻成不成立（M-公海-21）：有项目在订单阶段结束过，且没有项目还没结束。只用来判首次成立，成立后看成立日 */
export function 成交条件满足(项目们: readonly 三态项目[]): boolean {
  return 项目们.some((p) => p.阶段 === "订单" && p.结束) && 项目们.every((p) => p.结束);
}

/** 某套天数在普通 / 成交客户身上的三个节点（第几天）：成交只换活跃段，后两段间隔照那套 */
export function 节点天们(套: 三态天数, 成交活跃段: number | null): { 沉睡: number; 待回收: number; 进公海: number } {
  const 沉睡 = 成交活跃段 ?? 套.沉睡;
  const 待回收 = 沉睡 + (套.待回收 - 套.沉睡);
  return { 沉睡, 待回收, 进公海: 待回收 + 套.进公海 };
}

/**
 * 用哪套（M-公海-25）：项目里有外贸也有内贸取较长的一套（比最后进公海那天，再比待回收、沉睡）；
 * 只有外贸（可夹暂不分配）用外贸；没项目、全是暂不分配、只有内贸用内贸
 */
export function 选套(项目们: readonly 三态项目[], 规则: 三态规则, 成交活跃段: number | null): "内贸" | "外贸" {
  const 有内 = 项目们.some((p) => p.业务线 === "内贸"), 有外 = 项目们.some((p) => p.业务线 === "外贸");
  if (!有外) return "内贸";
  if (!有内) return "外贸";
  const a = 节点天们(规则.内贸, 成交活跃段), b = 节点天们(规则.外贸, 成交活跃段);
  const 外长 = b.进公海 !== a.进公海 ? b.进公海 > a.进公海 : b.待回收 !== a.待回收 ? b.待回收 > a.待回收 : b.沉睡 > a.沉睡;
  return 外长 ? "外贸" : "内贸";
}

/* ---------- 主函数 ---------- */

/**
 * 算一个客户今天的三态。
 * 归零日 = max(最近有内容的沟通, 最近项目推进, 最近一次算数的换负责人, 起算日)；起算日 = max(系统起算日, 导入完成日 + 30)。
 * 基准日 = 归零日 + 归零以后各次推后的天数（推后让三个节点一起顺延，钟不拨零，M-公海-19）。
 * 订单阶段项目的结束日并进「最近项目推进」（订单结束当天钟从 0 开始）。
 * 起算日：调用方应显式传 事实.系统起算日 = 组织规则里的起算日；不传才用常量 三态起算日。
 * 待回收提醒次数：调用方在钟归零时清零、每发一次 +1；3 次没发够不会判「该进公海」（M-公海-17）。
 */
export function 算三态(事实: 三态事实, 规则: 三态规则, 今天: string): 三态结果 {
  const 成交首次成立 = 事实.成交成立日 === null && 成交条件满足(事实.项目们);
  const 不计: 不计时原因 | null = !事实.有负责人 ? "没负责人" : 事实.在公海 ? "在公海" : 事实.已删 ? "已删" : 事实.无效 ? "无效" : 事实.负责人是市场 ? "市场成员名下" : null;
  if (不计) return { 计时: false, 原因: 不计, 成交首次成立 };

  const 按成交算 = 事实.成交成立日 !== null || 成交首次成立;
  const 活跃段 = 按成交算 ? 规则.成交.活跃段 : null;
  const 套 = 选套(事实.项目们, 规则, 活跃段);
  const 天 = 节点天们(规则[套], 活跃段);

  const 起算日 = 较晚(事实.系统起算日 ?? 三态起算日, 事实.导入完成日 ? 加天(事实.导入完成日, 导入豁免天数) : null)!;
  const 换人日 = 算数换负责人日(事实.换负责人们, 规则);
  const 订单结束日 = 较晚(...事实.项目们.filter((p) => p.阶段 === "订单" && p.结束).map((p) => p.结束日));
  const 归零日 = 较晚(事实.最近沟通日, 事实.最近推进日, 订单结束日, 换人日, 起算日)!;

  // 这一轮钟里的推后（归零那天及以前点的不算）；额度只认最近一次有内容的沟通以后的（换负责人不重置额度）
  const 本钟推后 = 事实.推后们.filter((x) => x.日 > 归零日);
  const 推后天 = 本钟推后.reduce((s, x) => s + x.天数, 0);
  const 基准日 = 加天(归零日, 推后天);
  const 第几天 = 差天(基准日, 今天);
  const 节点 = { 沉睡: 加天(基准日, 天.沉睡), 待回收: 加天(基准日, 天.待回收), 进公海: 加天(基准日, 天.进公海) };

  const 订单在推 = 事实.项目们.some((p) => p.阶段 === "订单" && !p.结束);
  const 到待回收 = !订单在推 && 第几天 >= 天.待回收;
  const 排期 = 到待回收 ? 排待回收提醒(节点, 今天, 事实.本轮待回收提醒次数, 事实.本轮最近待回收提醒日) : null;
  const 状态: 三态 = 订单在推 || 第几天 < 天.沉睡 ? "活跃" : 第几天 < 天.待回收 ? "沉睡" : 今天 < 排期!.最早进公海日 ? "待回收" : "该进公海";
  const 下一节点 = 订单在推 ? null : 状态 === "活跃" ? "沉睡" : 状态 === "沉睡" ? "待回收" : 状态 === "待回收" ? "进公海" : null;
  const 距下一节点 = 下一节点 === null ? null : 下一节点 === "进公海" ? 差天(今天, 排期!.最早进公海日) : 天[下一节点] - 第几天;
  const 被挡 = 状态 === "该进公海" && 事实.项目们.some((p) => !p.结束 && p.同事负责);

  // 继续持有额度（M-公海-19）
  const 额度推后 = 事实.推后们.filter((x) => 事实.最近沟通日 === null || x.日 > 事实.最近沟通日);
  const 已用次数 = 额度推后.length, 已用天数 = 额度推后.reduce((s, x) => s + x.天数, 0);
  const { 每次天数, 累计次数, 累计天数 } = 规则.继续持有;
  const 不能原因 =
    状态 !== "沉睡" && 状态 !== "待回收" ? "只有沉睡、待回收时能继续持有"
    : 本钟推后.some((x) => x.轮 === 状态) ? `${状态}这一轮已经继续持有过一次`
    : 已用次数 >= 累计次数 ? `继续持有已用满 ${累计次数} 次`
    : 已用天数 + 每次天数 > 累计天数 ? `继续持有合计最多顺延 ${累计天数} 天，已顺延 ${已用天数} 天`
    : null;
  const 继续持有: 继续持有额度 = { 已用次数, 已用天数, 剩次数: Math.max(0, 累计次数 - 已用次数), 剩天数: Math.max(0, 累计天数 - 已用天数), 能推: 不能原因 === null, 不能原因 };

  const 提醒 = 订单在推 ? null : 算提醒(状态, 第几天, 天, 今天, 被挡, 排期, 事实.暂缓回收日 ?? null);

  return { 计时: true, 状态, 第几天, 归零日, 基准日, 套, 按成交算, 成交首次成立, 节点, 节点天: 天, 下一节点, 距下一节点, 订单在推, 最早进公海日: 排期?.最早进公海日 ?? null, 被挡, 提醒, 继续持有, 算数换负责人日: 换人日 };
}

type 待回收排期 = { 今天发第几次: number | null; 最早进公海日: string };

/**
 * 待回收三次提醒怎么排（M-公海-17）：第 i 次的日子 = max(按规则排的那天〔待回收日 + 0 / 10 / 20〕, 上一次 + 间隔)；
 * 已经过了还没发的（漏跑一夜、改小天数当晚重算、订单结束后直接落在待回收后段）今天补发。
 * 最早进公海 = max(进公海节点, 第 3 次 + 间隔)。3 次没发够，天数到了也停在待回收
 */
function 排待回收提醒(节点: { 待回收: string; 进公海: string }, 今天: string, 已发: number, 最近发: string | null): 待回收排期 {
  const 次数 = 待回收提醒日.length;
  const 排的日 = (i: number) => 加天(节点.待回收, 待回收提醒日[i]);
  let 上次 = 已发 > 0 ? 最近发 ?? 排的日(Math.min(已发, 次数) - 1) : null;
  let 今天发第几次: number | null = null;
  for (let i = 已发; i < 次数; i++) {
    let 这次 = 排的日(i);
    if (上次 && 差天(上次, 这次) < 待回收提醒间隔) 这次 = 加天(上次, 待回收提醒间隔);
    // 只有下一次没发的可能已经到点 / 过点：今天发（过点的就是补发）；后面几次从今天起按间隔排，必然在今天以后
    if (i === 已发 && 这次 <= 今天) {
      今天发第几次 = i + 1;
      这次 = 今天;
    }
    上次 = 这次;
  }
  const 最后 = 上次 ?? 节点.待回收;
  return { 今天发第几次, 最早进公海日: 较晚(节点.进公海, 加天(最后, 待回收提醒间隔))! };
}

/** 今天该发哪条提醒（M-公海-17 / M-公海-27）；成交客户同一条链，按它自己的节点平移 */
function 算提醒(状态: 三态, n: number, 天: { 沉睡: number; 待回收: number; 进公海: number }, 今天: string, 被挡: boolean, 排期: 待回收排期 | null, 暂缓回收日: string | null): 今天提醒 | null {
  if (状态 === "沉睡") {
    const 沉睡第 = n - 天.沉睡;
    const 带上级 = 沉睡第 >= 沉睡抄上级第几天;
    const 主送: 提醒级[] = 带上级 ? ["本人", "直属上级"] : ["本人"];
    if (沉睡第 === 0) return { 事由: "进入沉睡", 主送, 抄送: [] };
    if (沉睡第 === 沉睡抄上级第几天) return { 事由: "沉睡抄上级", 主送, 抄送: [] };
    if (是周一(今天)) return { 事由: "沉睡周提醒", 主送, 抄送: [] };
    return null;
  }
  if (状态 === "待回收") {
    const 第几次 = 排期?.今天发第几次 ?? null;
    return 第几次 === null ? null : { 事由: "待回收提醒", 主送: ["条线总管理"], 抄送: ["本人", "直属上级"], 第几次 };
  }
  if (状态 === "该进公海" && 被挡 && 排期) {
    const 进公海日 = 排期.最早进公海日;
    // 裁决过「暂缓回收」的，从裁决那天起 30 天内不再推；否则从该进公海那天起每 30 天推一次，只发总管理
    const 起 = 暂缓回收日 && 暂缓回收日 >= 进公海日 ? 暂缓回收日 : 进公海日;
    const k = 差天(起, 今天);
    const 到点 = 起 === 进公海日 ? k >= 0 && k % 被挡提醒间隔 === 0 : k > 0 && k % 被挡提醒间隔 === 0;
    return 到点 ? { 事由: "被挡请裁决", 主送: ["条线总管理"], 抄送: [] } : null;
  }
  return null;
}
