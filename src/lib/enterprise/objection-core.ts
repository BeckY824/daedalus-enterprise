export type 不能自动退类 = (typeof 不能自动退类们)[number];

/** 撤回边界（判定页 #20）：项目还在接手人手里、没被并、没结束、没进公海，才自动退回。纯函数，库里读到的现状传进来 */
export type 对象现状 = { 已删除: boolean; 被并: boolean; 进公海: boolean; 已结束: boolean; 现负责人: string | null };
export function 算不能自动退(现状: 对象现状, 接手人: string): 不能自动退类 | null {
  if (现状.已删除) return "已删除";
  if (现状.被并) return "已并入";
  if (现状.进公海) return "进公海";
  if (现状.已结束) return "已结束";
  if (现状.现负责人 !== 接手人) return "已再转";
  return null;
}
