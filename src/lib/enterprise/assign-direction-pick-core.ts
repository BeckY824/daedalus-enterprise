/**
 * 市场成员指定分配按方向挑人（P-转-26，11-18）的纯函数部分：界面（转让框）和服务端（assign-direction-pick.ts）共用，不碰库
 */
import { 两条线 } from "./assign-line";
import type { 线 } from "./lead-assign";

/** 每条线指定分配能挑的人（已叠参与状态正常） */
export type 指定候选表 = Record<线, string[]>;

/** 这个方向能挑的人：判不出方向（null）= 两条线并起来 */
export const 按方向挑 = (表: 指定候选表, 向: 线 | null): string[] => (向 ? 表[向] : [...new Set(两条线.flatMap((l) => 表[l]))]);

/** 新线索向导「指定分配」选的负责人不在所选方向能挑的人里（P-转-26，11-20 3703 实操） */
export const 新建方向不符话 = (向: 线): string => `负责人不在所选方向（${向}），请改方向或换人`;

export const 指定方向话 = (向: 线 | null): string =>
  向 === "内贸" ? "按分配方向（内贸）只能指定给内贸事业部的销售、销售管理"
    : 向 === "外贸" ? "按分配方向（外贸）只能指定给外贸事业部的销售、销售管理"
      : "只能指定给内贸、外贸事业部正常参与分配的销售";
