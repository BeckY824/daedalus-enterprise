/**
 * 设置页按登录身份显示（P-界面-46，用户 11-15「目前身份都是确认的，就按身份来看」）：这个人进设置看到哪几块、能不能改。
 * 页面（SettingsBody）和测试都只认这一处；服务端各个写入口照旧各自拦（能改后台设置 / 挡改设置 / team-scope 只读拦）。
 *
 *   系统管理员（director 没设线或带标记、没勾「不管设置」）：后台设置全看、全改
 *   只读管理员（admin、不兼 director、没设业务线 = 能看全部）：后台设置看得见、一律灰（11-01「可以看所有。但不能做任何编辑」）；
 *     设了业务线的管理员只看那条线，全公司的设置和日志不给他，照「成员」走
 *   其余（条线总管理、销售管理、市场管理、销售……）：个人几项 + 自己能改的（比如给下属设线索配额）+「我能做什么」
 * 不是企业版：照老规矩账号 ADMIN 全看全改，别人只个人
 */
import { 能改后台设置, 能看全部, 能进设置, 只读角色, type 谁 } from "./permissions";
import type { 组织 } from "./org-core";

export type 设置身份 = "系统管理员" | "只读管理员" | "成员";

export type 设置范围 = {
  身份: 设置身份;
  /** 后台设置那几栏（成员、组织架构、项目模式、客户回收、AI、业务配置、操作日志）看不看得到 */
  可看: boolean;
  /** 后台设置改不改得了 */
  可改: boolean;
  /** 看得到、改不了：控件一律灰（只读管理员） */
  只读: boolean;
  /** 只给个人几项（加自己能改的那几项） */
  只个人: boolean;
};

export function 设置范围of(me: 谁 & { role?: string | null }, org: 组织 | null, 企业版: boolean): 设置范围 {
  if (!企业版) {
    const 老板 = me.role === "ADMIN";
    return { 身份: 老板 ? "系统管理员" : "成员", 可看: 老板, 可改: 老板, 只读: false, 只个人: false };
  }
  const 可改 = 能改后台设置(me, org);
  const 可进 = 能进设置(me, org);
  const 只读看 = !可进 && 只读角色(me, org) && 能看全部(me, org);
  const 可看 = 可进 || 只读看;
  return {
    身份: 可进 ? "系统管理员" : 只读看 ? "只读管理员" : "成员",
    可看,
    可改,
    只读: 可看 && !可改,
    只个人: !可看,
  };
}
