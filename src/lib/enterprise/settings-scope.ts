export function 我能做什么(角色们: readonly string[], 身份: 设置身份, 条线: boolean): 能做项[] {
  if (身份 === "系统管理员") return 各角色.director;
  const 键们: (角色键 | "条线总管理")[] = 角色们.flatMap((r) => (r === "director" ? (条线 ? ["条线总管理" as const] : []) : r in 各角色 ? [r as 角色键] : []));
  if (!键们.length) return [{ 事: "看公海", 能: true }, { 事: "其他操作", 能: false, 注: "还没设业务角色，请找总管理设置" }];
  const 合: 能做项[] = [];
  for (const k of 键们) for (const x of 各角色[k]) {
    const 有 = 合.find((y) => y.事 === x.事);
    if (!有) 合.push({ ...x });
    else if (x.能 && !有.能) Object.assign(有, x);
  }
  return 合;
}

