const 天 = 86_400_000;
const 京偏 = 8 * 3_600_000;

/** 'YYYY-MM-DD' → 那天 UTC 零点的毫秒（只当日历用） */
const 日数 = (d: string): number => Date.UTC(+d.slice(0, 4), +d.slice(5, 7) - 1, +d.slice(8, 10));
const 日串 = (ms: number): string => new Date(ms).toISOString().slice(0, 10);

/** 展开后的：年份 → { 放假天们, 上班天们 } */
const 展开 = new Map<number, { 放假: Set<string>; 上班: Set<string> }>();
for (const [年, 表] of Object.entries(节假日表)) {
  const 放假 = new Set<string>();
  for (const [起, 止] of 表.放假) for (let t = 日数(起); t <= 日数(止); t += 天) 放假.add(日串(t));
  展开.set(Number(年), { 放假, 上班: new Set(表.上班) });
}

/** 这一年录没录节假日安排 */
export const 有节假日表 = (年: number): boolean => 展开.has(年);

/** 一个瞬间在北京是哪天（YYYY-MM-DD） */
export const 北京日 = (t: Date): string => 日串(t.getTime() + 京偏);

/** 没录的年份只提醒一次（钟一分钟一遍，别刷屏） */
const 提醒过缺表 = new Set<number>();

/** 北京这一天（YYYY-MM-DD）上不上班：放假 → 否；调休上班 → 是；其余周一到周五是；表里没这一年按周一到周五兜底 */
export function 是工作日(日: string): boolean {
  const 年 = +日.slice(0, 4);
  const 表 = 展开.get(年);
  if (表) {
    if (表.放假.has(日)) return false;
    if (表.上班.has(日)) return true;
  } else if (!提醒过缺表.has(年)) {
    提醒过缺表.add(年);
    console.warn(`[工作日] ${年} 年的法定节假日安排还没录（lib/enterprise/cn-workday.ts 节假日表），先按周一到周五算；国务院办公厅通知发布后请录入`);
  }
  const 周 = new Date(日数(日)).getUTCDay();
  return 周 !== 0 && 周 !== 6;
}

/** 这一天的下一天（YYYY-MM-DD） */
export const 下一天 = (日: string): string => 日串(日数(日) + 天);
/** 这一天的前一天（YYYY-MM-DD） */
export const 前一天 = (日: string): string => 日串(日数(日) - 天);
