/** 一项字典的释义：只认默认 id（dict-<类>-<序号>），自己加的、没写释义的 = null。纯函数，界面和服务端都能用 */
export function 字典项释义(kind: 字典种类, id: string): string | null {
  const m = /^dict-([A-Za-z]+)-(\d+)$/.exec(id);
  if (!m || m[1] !== kind) return null;
  return 字典定义[kind].释义?.[Number(m[2])] ?? null;
}

