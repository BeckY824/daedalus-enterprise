export type 验号结果 =
  /** 值 = 存进库的样子；键 = 查重比对用的（不分大小写的已经小写） */
  | { ok: true; 类型: 号码类型; 值: string; 键: string; 国外?: boolean }
  | { ok: false; 状态: "未选类型" | "无法识别" | "格式错误" | "待上传"; 提示: string };

const 错 = (类型: 号码类型): 验号结果 => ({ ok: false, 状态: "格式错误", 提示: 号码提示.格式错误[类型] });
const 认不出: 验号结果 = { ok: false, 状态: "无法识别", 提示: 号码提示.无法识别 };

/** 全角数字、全角加号、全角冒号换成半角 */
function 半角(s: string): string {
  return 全角数字转半角(s).replace(/＋/g, "+").replace(/：/g, ":");
}

/**
 * 手机号（B1 / B2）。分隔符（空格、横杠、括号、点）去掉；00 开头当 +。
 * 去完还夹着字母、汉字的算格式错误（不猜，和 lib/phone 的「号码中间夹字母不猜」一个意思）
 */
function 验手机(原: string, 放过占位 = false): 验号结果 {
  const r = 验手机格式(原);
  // 占位假号（P-全局-06）：建档向导、AI 建档、线索录入、号码子表、客户电话都走这里。看规整后的号（+86 / 0086 去掉以后），拦下、叫人填真实号码
  if (r.ok) return !放过占位 && 是占位号(r.值) ? 占位错 : r;
  // 「11111111111」「12345678901」这类 11 位、不是 1[3-9] 开头的占位号：照旧说是占位号（比「格式错误」好懂）；放过占位（老数据原样留着）的照旧收。
  // 只认 11 位：短的「123456」「87654321」照旧说格式错误、像座机
  if (r.状态 !== "格式错误") return r;
  const 号 = 半角(原).trim().replace(/[\s\-()（）.－—–‐‑‒―]/g, "").replace(/^(?:\+|00)?86(?=\d{11}$)/, "");
  if (!/^\d{11}$/.test(号) || !是占位号(号)) return r;
  return 放过占位 ? { ok: true, 类型: "手机号", 值: 号, 键: 号 } : 占位错;
}
const 占位错: 验号结果 = { ok: false, 状态: "格式错误", 提示: `⚠️${占位号提示("手机号")}` };

/**
 * 手机号里有字母或汉字（11-17 员工反馈：电话格贴了微信号「sqin175…」，原来截出里面的数字存成了手机号）：不截数字，整格拒，
 * 叫人去联系方式里选「微信」类型
 */
export const 像微信号提示 = "格式不对，像微信号？请到联系方式里选「微信」类型";
/** 手机号那格填的像座机（0 开头带区号、或 7–8 位本地号）：叫人改选座机类型 */
export const 像座机提示 = "像座机，请选座机类型";

/**
 * 香港 / 澳门手机号没带区号（11-18 员工反馈：8 位港号原来说「像座机」，人不知道要加 +852）。
 * 8 位、5 / 9 开头的说像香港号；6 开头的港澳都有（澳门手机 6 开头）；别的 8 位照旧说像座机。
 * 国内不带区号的本地座机也有 5、6、9 开头的，提示后半句留着「座机请改选座机类型」
 */
export const 像香港号提示 = "像香港号码？请加 +852（座机请改选座机类型）";
export const 像港澳号提示 = "像香港 / 澳门号码？请加 +852 或 +853（座机请改选座机类型）";
function 港澳提示(s: string): string | null {
  if (/^[59]\d{7}$/.test(s)) return 像香港号提示;
  if (/^6\d{7}$/.test(s)) return 像港澳号提示;
  return null;
}

/** 去掉分隔符后的号像国内座机：0 + 区号（10–12 位）、不带区号的 7–8 位本地号、+86 后面是区号座机 */
function 像座机(s: string): boolean {
  if (/^0[1-9]\d{8,10}$/.test(s) || /^[2-9]\d{6,7}$/.test(s)) return true;
  return /^\+86(?:10|2\d|[3-9]\d{2})\d{7,8}$/.test(s);
}

/** 大陆手机号：1 开头、第二位 3–9、共 11 位 */
export const 大陆手机 = /^1[3-9]\d{9}$/;

/** 表格把长号存成数字后的科学计数法（「8.61391E+12」）：后几位已经丢了 */
export const 科学计数提示 = "像是表格改成科学计数法的号（后几位已经丢了），请填完整号码";

function 验手机格式(原: string): 验号结果 {
  let s = 半角(原).trim().replace(/^'/, "");
  if (s.includes("*")) return 认不出;
  if (/^\+?\d+(?:\.\d+)?[Ee]\+?\d{1,2}$/.test(s)) return { ok: false, 状态: "格式错误", 提示: 科学计数提示 };
  s = s.replace(/[\s\-()（）.－—–‐‑‒―]/g, "");
  // 「无」「暂无」「N/A」这类写着没有的：认不出（同空），不说像微信号
  if (/^(?:无|没有|暂无|空|不详|未知|n\/?a|none|null)$/i.test(s)) return 认不出;
  if (/\p{L}/u.test(s)) return { ok: false, 状态: "格式错误", 提示: 像微信号提示 };
  if (!/\d/.test(s)) return 认不出;
  s = s.replace(/^00(?=\d)/, "+");
  if (!/^\+?\d+$/.test(s)) return 错("手机号");
  // +86 13900000101 / 0086… / 86… 后面正好 11 位：国内号，存 11 位（和 规整手机号 一样）
  const 国内 = s.replace(/^\+?86(?=\d{11}$)/, "");
  if (大陆手机.test(国内)) return { ok: true, 类型: "手机号", 值: 国内, 键: 国内 };
  // 像港澳手机没带区号（11-18）：叫人加 +852 / +853；像座机（0 开头带区号、7–8 位本地号、+86 后面是区号座机）：叫人改选座机类型（11-17）
  const 港澳 = 港澳提示(s);
  if (港澳) return { ok: false, 状态: "格式错误", 提示: 港澳 };
  if (像座机(s)) return { ok: false, 状态: "格式错误", 提示: 像座机提示 };
  // +86 后面不是手机号、没有 + 的 11 位不是 1[3-9] 开头的：国内号不对，不当国外号放过去
  if (/^\+86/.test(s) || !s.startsWith("+")) return 错("手机号");
  if (/^\+\d{8,15}$/.test(s)) return { ok: true, 类型: "手机号", 值: s, 键: s.slice(1), 国外: true };
  return 错("手机号");
}

/**
 * 客户「电话」那一格（客户页就地改、完整表单，11-17）：和建档向导、联系人表单同一套手机号规矩（验号码 手机号）。
 * 空 = 没填（必填不必填调用方按「还有没有别的联系方式」判，M-必填-01）。错话不带 ⚠️（写在格子下面）
 */
export function 验客户电话(原: string | null | undefined, 选项: { 放过占位?: boolean } = {}): { ok: true; 值: string; 键: string; 国外?: boolean } | { ok: false; error: string } {
  const s = (原 ?? "").trim();
  if (!s) return { ok: true, 值: "", 键: "" };
  const r = 验号码("手机号", s, 选项);
  if (r.ok) return { ok: true, 值: r.值, 键: r.键, ...(r.国外 ? { 国外: true } : {}) };
  const 话 = r.提示.replace(/^⚠️/, "");
  return { ok: false, error: r.状态 === "格式错误" && r.提示 === 号码提示.格式错误.手机号 ? 电话格式话 : 话 };
}
export const 电话格式话 = "电话格式不对：国内手机号 11 位（1 开头），国外号码 + 开头、8–15 位数字";

/** 邮箱（B3）。只去首尾空格；中间有空格算错 */
function 验邮箱(原: string): 验号结果 {
  const s = 原.trim();
  if (!s) return 认不出;
  if (s.includes("*")) return 认不出;
  const 好 =
    !/\s/.test(s) &&
    !s.includes("..") && !/[。．]/.test(s) &&
    s.split("@").length === 2 &&
    (() => {
      const [本地, 域] = s.split("@");
      if (!本地 || !域 || 域.startsWith(".") || !域.includes(".")) return false;
      // 最后一段 2–24 个字母（.photography、.international 这类长后缀，11-17），或国际化域名的 xn-- 写法
      return /^(?:[A-Za-z]{2,24}|xn--[A-Za-z0-9-]{1,59})$/.test(域.slice(域.lastIndexOf(".") + 1));
    })();
  return 好 ? { ok: true, 类型: "邮箱", 值: s, 键: s.toLowerCase() } : 错("邮箱");
}

/**
 * 微信号（B4）。只去首尾空格；不分大小写比（和外贸的微信查重同一个键法）。认三种（11-17，M-导入-43 ⑤）：
 * 字母开头 6–20 位字母、数字、_、-；拿大陆手机号当微信号的（存 11 位，+86 / 空格横杠去掉）；5–11 位纯数字、不以 0 开头（QQ 号那样的）。
 * 纯数字的是占位假号（全同、顺序）拦下
 */
function 验微信(原: string): 验号结果 {
  const s = 原.trim();
  if (!s || s.includes("*")) return 认不出;
  if (/^[a-zA-Z][a-zA-Z0-9_-]{5,19}$/.test(s)) return { ok: true, 类型: "微信", 值: s, 键: s.toLowerCase() };
  const 数 = 半角(s).replace(/[\s\-－—–]/g, "");
  const 手机 = /^(?:\+|00)?(?:86)?(1[3-9]\d{9})$/.exec(数);
  const 值 = 手机 ? 手机[1] : /^[1-9]\d{4,10}$/.test(数) ? 数 : null;
  if (!值) return 错("微信");
  if (是占位号(值)) return { ok: false, 状态: "格式错误", 提示: `⚠️${占位号提示("微信号")}` };
  return { ok: true, 类型: "微信", 值, 键: 值 };
}

/**
 * 旺旺 ID（B5）：先去掉空格和符号（留字母、数字、_、- 和子账号的 :），再看 4–30 位、最多一个 :。
 * 「主账号:子账号」是两个不同的人，查重整串比，主账号不认成子账号。不分大小写
 */
function 验旺旺(原: string): 验号结果 {
  const t = 半角(原);
  if (t.includes("*")) return 认不出;
  // 横杠留着（11-17：「ab-cd」是两个不同的账号写法，去掉就和「abcd」撞了）
  const s = t.replace(/[\s\p{P}\p{S}]/gu, (c) => (c === "_" || c === ":" || c === "-" ? c : ""));
  if (!s.replace(/[_:-]/g, "")) return 认不出;
  const 好 = s.length >= 4 && s.length <= 30 && /^[a-zA-Z0-9_-]+(:[a-zA-Z0-9_-]+)?$/.test(s);
  return 好 ? { ok: true, 类型: "旺旺ID", 值: s, 键: s.toLowerCase() } : 错("旺旺ID");
}

/**
 * 按选的类型验一个号码。二维码看 有图（号码那格不用填）；其余类型 有图 不看
 */
export function 验号码(类型: unknown, 原: unknown, 选项: { 有图?: boolean; 放过占位?: boolean } = {}): 验号结果 {
  if (!是号码类型(类型)) return { ok: false, 状态: "未选类型", 提示: 号码提示.未选类型 };
  if (类型 === "二维码") {
    return 选项.有图 ? { ok: true, 类型, 值: "", 键: "" } : { ok: false, 状态: "待上传", 提示: 号码提示.待上传 };
  }
  const s = typeof 原 === "string" ? 原 : "";
  if (类型 === "手机号") return 验手机(s, 选项.放过占位);
  if (类型 === "邮箱") return 验邮箱(s);
  if (类型 === "微信") return 验微信(s);
  return 验旺旺(s);
}

