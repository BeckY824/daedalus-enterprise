/**
 * 企业版：客户在客户公海里的项目不单独领、不单独分（M-公海-06）。放开了会项目有人、客户还在公海（X-13 那种）。
 * 开关 领项目带走单项目客户 开着时领项目会把客户一起带走，不算拆开，不拦
 */
export function 拦客户公海里的项目(客户在公海: boolean): boolean {
  return 企业版() && 客户在公海 && !公海规则.领项目带走单项目客户;
}

/** 企业版、且规则不让单独领项目 */
