/** 一格（国家 / 省 / 市 / 区县）是不是港澳台：「香港」「中国香港」「台湾省」「澳門特別行政區」「台北市」「灣仔區」「九龙」……；不是 = null。英文写法在 customer-region.ts */
export function 港澳台地名(x: string | null | undefined): 港澳台 | null {
  const t = 简(String(x ?? "").trim()).replace(/^中国\s*/, "");
  if (!t) return null;
  const 头 = t.match(/^(香港|澳门|台湾)/);
  if (头) return 头[1] as 港澳台;
  return 港澳台查.get(t) ?? null;
}

const 去后缀 = (x: string) => x.replace(/(特别行政区|维吾尔自治区|壮族自治区|回族自治区|自治区|自治州|地区|省|市|盟)$/, "");

/** 一格（省或市）是不是确定的中国大陆地名；港澳台、外国城市、认不出的 = false */
export function 像国内地名(x: string | null | undefined): boolean {
  const t = 简(String(x ?? "").trim());
  if (!t || 港澳台地名(t)) return false;
  const k = 去后缀(t);
  return 省名.has(k) || 市名.has(k) || 市名.has(t) || 县级市.has(k);
}

