const 去后缀 = (x: string) => x.replace(/(特别行政区|维吾尔自治区|壮族自治区|回族自治区|自治区|自治州|地区|省|市|盟)$/, "");

/** 一格（省或市）像不像国内地名 */
export function 像国内地名(x: string | null | undefined): boolean {
  const t = String(x ?? "").trim();
  if (!t) return false;
  if (港澳台.test(t)) return true;
  const k = 去后缀(t);
  return 省名.has(k) || 市名.has(k) || 市名.has(t) || /^[\u4e00-\u9fff]{1,8}(市|县|区)$/.test(t);
}

