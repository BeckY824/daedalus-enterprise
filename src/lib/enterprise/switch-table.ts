/**
 * 拨一个开关前后果框里说什么（总览和原卡同一套，N6）。
 * 上下文：全员人数；按组织架构看客户开没开（往前推权限要）；开着的子开关（关父开关时写「连带」）；打开时要提醒的没备好的依赖
 */
export function 开关后果of(
  k: 开关键,
  目标: boolean | string,
  上下文: { 全员?: number; 按组织看客户?: boolean; 开着的子开关?: readonly 开关键[]; 注意?: readonly string[]; 节点推进范围?: "全部" | "新建" } = {},
): 开关后果 {
  const s = 开关of[k];
  const 后果: 后果一条[] = [];
  if (s.opts) {
    const 值 = String(目标);
    后果.push({ 标: "会怎样", 级: "警", 话: s.opts.find(([v]) => v === 值)?.[1] ?? 值 });
    if (值 === "仅上级推" && 上下文.按组织看客户 === false) 后果.push({ 标: "注意", 级: "警", 话: "「按组织架构看客户」关着，选了也不起作用，谁的项目谁推" });
    else if (值 === "仅上级推") 后果.push({ 标: "依赖", 话: "跟着「按组织架构看客户」走；只对有直属上级的负责人生效；总管理照旧能推" });
    后果.push({ 标: "影响谁", 话: 影响话(s, 上下文.全员) }, { 标: "生效", 话: s.when });
    return { 题: `「${s.名}」改成「${值}」？`, 后果, 是: "确认改", 危: false };
  }
  const 开 = 目标 === true;
  if (开) {
    后果.push({ 标: "会怎样", 级: s.危 ? "危" : "警", 话: s.what.replace(/^开着：/, "") });
    if (s.openExtra) 后果.push({ 标: "注意", 级: "警", 话: s.openExtra });
    for (const x of 上下文.注意 ?? []) 后果.push({ 标: "注意", 级: "警", 话: x });
  } else {
    后果.push({ 标: "会怎样", 级: "警", 话: s.off ?? `关掉以后不再按「${s.名}」管` });
    const 跟 = (上下文.开着的子开关 ?? []).map((x) => 开关of[x].名);
    if (跟.length) 后果.push({ 标: "连带", 级: "警", 话: `「${跟.join("」「")}」跟着不起作用，开关值留着（还能单独关掉）` });
  }
  后果.push({ 标: "影响谁", 话: 影响话(s, 上下文.全员) });
  const 生效 = k === "node_advance" && 开
    ? (上下文.节点推进范围 === "新建" ? "只管开启之后新建的项目" : "立即；存量项目下次保存或点「完成节点」时按必填走")
    : 开 ? s.when : "立即";
  后果.push({ 标: "生效", 话: 生效 });
  return { 题: `${开 ? "打开" : "关掉"}「${s.名}」？`, 后果, 是: 开 ? "确认打开" : "确认关掉", 危: !开 || !!s.危 };
}

