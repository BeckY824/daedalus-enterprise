/**
 * 客户三态在列表、看板上的标（P-界面-19 ①②，构想页 C2 / C5）：浏览器、服务端共用的叫法和说明，不碰库。
 * 活跃不标；沉睡 / 待回收 / 暂缓回收中各一个小标签（待回收带「N 天后进公海」）；负责人是市场成员的写「不计时」（M-公海-34）。
 * 取数在 tri-state-list.ts（只在服务端用）
 *
 * 状态码（库里的钟、留痕、地址栏 triState=、CSS 类名）照旧是 活跃 / 沉睡 / 待回收 / 暂缓回收中；
 * 给人看的叫法（11-12 用户定）一律走 三态叫法：正常跟进 / 沉睡待定 / 即将回收 / 暂缓待收。
 * 按钮「暂缓回收」是动作、不是状态，名字不变（故意和状态「暂缓待收」不同名）
 */

/** 状态码 → 界面上的叫法（只改叫法，码不动） */
export const 三态叫法 = { 活跃: "正常跟进", 沉睡: "沉睡待定", 待回收: "即将回收", 暂缓回收中: "暂缓待收" } as const;
/** 被挡时总管理那颗按钮的名字（动作，不跟状态改名） */
export const 暂缓回收按钮名 = "暂缓回收";
/** 状态码 → 叫法；不认识的码（公海、该进公海、不计时……）原样给 */
export const 三态显示名 = (码: string): string => (三态叫法 as Record<string, string>)[码] ?? 码;
/**
 * 系统写进库里的那几句（留痕理由：进入沉睡、待回收满…）是旧叫法，显示时换成新叫法；库里不改。
 * 「暂缓回收」是动作名，不换；已经是新叫法的（沉睡待定）不重复换；「沉睡线 / 沉睡期」照旧
 */
export const 换成新叫法 = (s: string): string => {
  const 进公海句 = 进公海理由显示(s);
  return 进公海句 !== s ? 进公海句 : s.replace(/暂缓回收中|暂缓回收(?=解除|已解除)/g, 三态叫法.暂缓回收中).replace(/，暂缓回收，/g, `，进入${三态叫法.暂缓回收中}，`).replace(/待回收/g, 三态叫法.待回收).replace(/沉睡(?!待定|线|期)/g, 三态叫法.沉睡).replace(/活跃(?!段)/g, 三态叫法.活跃);
};

/** 自动进客户公海那一句（tri-state-db.ts 三态进公海理由写进 CustomerPool.reason、项目 pool-release、状态留痕）；「自动进客户公海」几个字别动，自动收回次数按它认（tri-state-quota.ts 自动进公海说法） */
export const 进公海理由句 = (进公海天数: number) => `进入${三态叫法.待回收}满 ${进公海天数} 天、3 次提醒都没人处理，自动进客户公海`;
/** 认这一句：库里老行「待回收满」、上一版「即将回收满」、现在的「进入即将回收满」；整句对得上才算，人写的理由碰巧带这几个字不动 */
const 进公海句式 = /^(?:待回收满|即将回收满|进入即将回收满) (\d+) 天、3 次提醒都没人处理，自动进客户公海$/;
/**
 * 公海标签悬停（客户列表、客户详情）、项目进程变更里回公海那一行显示 reason 用它：只换系统写的那一句的叫法，别的理由（手动放回写的、超时…）原样
 */
export const 进公海理由显示 = (s: string): string => {
  const m = 进公海句式.exec(s.trim());
  return m ? 进公海理由句(Number(m[1])) : s;
};

/** 列表「全部回收状态」能筛的几个值（地址栏 triState=），同构想页 C2 的下拉 */
export const 三态筛选值们 = ["沉睡", "待回收", "暂缓回收中", "不计时"] as const;
export type 三态筛选值 = (typeof 三态筛选值们)[number];
export const 是三态筛选值 = (v: unknown): v is 三态筛选值 => typeof v === "string" && (三态筛选值们 as readonly string[]).includes(v);

/** 一位客户的标：活跃没有标（不给） */
export type 三态标 = { 态: 三态筛选值; /** 待回收：按钟上的进入日和这位客户适用那套天数，还有几天到进公海那天（≤0 = 到了，等提醒发够） */ 几天后进公海?: number };

/** 标签上的字 */
export function 三态标字(x: 三态标): string {
  const 名 = 三态显示名(x.态);
  if (x.态 !== "待回收") return 名;
  const n = x.几天后进公海;
  if (n === undefined) return 名;
  return n > 0 ? `${名} · ${n} 天后进公海` : `${名} · 马上进公海`;
}

/** 悬停说明 */
export function 三态标说明(x: 三态标): string {
  switch (x.态) {
    case "沉睡": return `${三态叫法.沉睡}：很久没有有效沟通，也没有项目推进`;
    case "待回收": return x.几天后进公海 !== undefined && x.几天后进公海 > 0
      ? `${三态叫法.待回收}：再没有有效沟通，${x.几天后进公海} 天后自动进客户公海`
      : `${三态叫法.待回收}：已到进公海的天数，提醒发够后自动进客户公海`;
    case "暂缓回收中": return `${三态叫法.暂缓回收中}：到期该进公海，名下有同事在推的项目，等条线总管理裁决`;
    case "不计时": return "负责人是市场成员，不计回收时间";
  }
}

/** 看板卡片上点不点色点：沉睡、待回收、暂缓回收中点；不计时不点 */
export const 看板要点 = (x: 三态标 | undefined): x is 三态标 => !!x && x.态 !== "不计时";
