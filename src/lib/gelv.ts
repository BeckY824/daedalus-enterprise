/**
 * 字段名占几个汉字宽（13px 字号下拉丁字母、数字约 0.6 个字宽），落到 4 / 5 / 6 三档。
 * 卡片按里面最长那个字段名的档定字段名列宽（gelv-preview.css 用 :has([data-fl]) 选，6 档以上的折行）
 */
export function 字段名档(名: string): 4 | 5 | 6 {
  let 宽 = 0;
  for (const ch of 名) 宽 += /[\u0000-ɏ]/.test(ch) ? 0.6 : 1;
  return 宽 <= 4 ? 4 : 宽 <= 5 ? 5 : 6;
}
